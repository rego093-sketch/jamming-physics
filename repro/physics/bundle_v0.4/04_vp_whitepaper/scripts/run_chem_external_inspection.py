#!/usr/bin/env python3
"""Bulk literature inspection validator for VP chemistry (Sec.18).

This script consumes a DOI-embedded CSV dataset containing (P_IDX, OBS_REF_AMP)
for a broad set of species and produces deterministic summary outputs.

Inputs (locked):
- 04_vp_whitepaper/LOCK/chem_external_inspection_lock.json
- 04_vp_whitepaper/data/chem/external_inspection/VP_STEP7_EXT_INSPECTION_FULL_V1.csv

Outputs:
- 04_vp_whitepaper/outputs/chem/external_inspection_rows.json
- 04_vp_whitepaper/outputs/chem/external_inspection_summary.json
- 04_vp_whitepaper/outputs/chem/table_external_inspection_summary.tex
- gate/reports/gate_report_chem_external_inspection.json

The gate is an **integrity** gate:
- it checks that the dataset is internally consistent with its declared rule
  (CALC_AMP, ERROR(%), STATUS vs tolerance)
- it does NOT require all rows to PASS as chemistry (the dataset intentionally
  contains explicit failures/boundary cases).

No non-std dependencies.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import math
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Dict, List, Tuple


# ----------------------------
# Utilities
# ----------------------------

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding='utf-8'))


def write_json(path: Path, obj: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding='utf-8')


def protocol_created(bundle_root: Path) -> str:
    """Deterministic date for reproducibility (preferred over wall-clock time)."""
    p = bundle_root / "registry" / "protocol_lock.json"
    if p.exists():
        try:
            v = load_json(p).get("created")
            if v:
                return str(v)
        except Exception:
            pass
    return str(date.today())


def read_csv_allow_comments(path: Path) -> List[dict]:
    """Read CSV while skipping comment/blank lines.

    Lines starting with '#' are ignored.
    """
    buf_lines: List[str] = []
    for ln in path.read_text(encoding='utf-8').splitlines():
        s = ln.strip()
        if not s:
            continue
        if s.startswith('#'):
            continue
        buf_lines.append(ln)
    if not buf_lines:
        return []
    reader = csv.DictReader(io.StringIO("\n".join(buf_lines)))
    rows: List[dict] = []
    for row in reader:
        cleaned = {k.strip(): (v.strip() if isinstance(v, str) else v) for k, v in row.items()}
        rows.append(cleaned)
    return rows


def pct(x: float) -> float:
    return 100.0 * x


@dataclass
class RowCheck:
    id: str
    ok: bool
    label: str
    got: float
    expected: float
    tol: float


