def slugify(title, number):
    s = title.lower().encode("ascii","ignore").decode("ascii")
    s = re.sub(r"[^a-z0-9]+","-",s).strip("-")
    words = [w for w in s.split("-") if w and w not in STOPWORDS][:5]
    return "%02d-%s" % (number, "-".join(words))

def seo_meta(title_text, desc_text, url, og_type="article", extra_keywords=None):
    """Discovery meta block shared by every page type: keywords, author, robots, Open Graph, Twitter.
    Deterministic (no wall-clock); attributes are HTML-escaped; conclusion-first description supplied by caller."""
    kws = list(KEYWORDS_BASE)
    for k in (extra_keywords or []):
        kp = html.unescape(re.sub("<[^>]+>", "", k)).strip()
        if kp and kp not in kws:
            kws.append(kp)
    kw = html.escape(", ".join(kws))
    t  = html.escape(title_text)
    d  = html.escape(desc_text)
    u  = html.escape(url)
    return (
        '<meta name="keywords" content="' + kw + '">\n'
        '<meta name="author" content="' + html.escape(AUTHOR) + '">\n'
        '<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">\n'
        '<meta property="og:type" content="' + og_type + '">\n'
        '<meta property="og:site_name" content="' + html.escape(SITE_NAME) + '">\n'
        '<meta property="og:locale" content="en_US">\n'
        '<meta property="og:title" content="' + t + '">\n'
        '<meta property="og:description" content="' + d + '">\n'
        '<meta property="og:url" content="' + u + '">\n'
        '<meta name="twitter:card" content="summary">\n'
        '<meta name="twitter:title" content="' + t + '">\n'
        '<meta name="twitter:description" content="' + d + '">\n')

