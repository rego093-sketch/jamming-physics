def m(x):                       # inline math span (counted as eq_inline)
    return '<span class="m">%s</span>' % x
def tbl(headers, rows):
    h = "".join("<th>%s</th>" % html.escape(str(c)) for c in headers)
    body = ""
    for r in rows:
        body += "<tr>" + "".join("<td>%s</td>" % c for c in r) + "</tr>"
    return '<table><thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (h, body)

GRADE_CLASS = {"[F]":"g-forced","[V]":"g-verified","[H]":"g-hypothesis",
               "[L]":"g-calibrated","[O]":"g-open"}
GRADE_WORD  = {"[F]":"forced","[V]":"verified","[H]":"hypothesis",
               "[L]":"calibrated (literature-anchored)","[O]":"open"}
GRADE_PRIORITY = ["[F]","[V]","[H]","[L]","[O]"]

def page_grade(tokens):
    if not tokens: return None
    from collections import Counter
    c = Counter(tokens)
    best = max(c.values())
    tied = [t for t in GRADE_PRIORITY if c.get(t,0) == best]
    return tied[0] if tied else None

