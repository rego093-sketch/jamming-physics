# --------------------------------------------------------------------------- writer
def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

def main():
    locked, why = gates.writing_locked()
    if locked:
        print("REFUSED: writing is locked.\nReason:", why)
        print("Sign off research first: gates.write_research_complete(), then  echo writing > PHASE")
        return 1

    D = gather()
    S = build_sections(D)

    # per-section pages
    for i, s in enumerate(S):
        prev = S[i - 1] if i > 0 else None
        nxt  = S[i + 1] if i < len(S) - 1 else None
        write(os.path.join(_DOCS, PAPER_ID, s["slug"], "index.html"), render_chapter(s, prev, nxt))

    # hub, meta, top index, sitemap, robots, llms, css
    write(os.path.join(_DOCS, PAPER_ID, "index.html"), render_hub(S, D))
    write(os.path.join(_DOCS, PAPER_ID, "_meta.json"),
          json.dumps(render_meta(S, D), ensure_ascii=False, indent=2))
    write(os.path.join(_DOCS, "index.html"), render_index(S, D))
    write(os.path.join(_DOCS, "sitemap.xml"), render_sitemap(S))
    write(os.path.join(_DOCS, "robots.txt"), render_robots())
    write(os.path.join(_DOCS, "llms.txt"), render_llms(S, D))
    write(os.path.join(_DOCS, "assets", "css", "site.css"), render_css())

    # manifest CSV (derived index of the canonical HTML)
    rows = ["slug,title,section_no,status,grade,words,eq_display"]
    for s in S:
        rows.append("%s,%s,%d,published,%s,%d,0" % (
            s["slug"], '"' + plain(s["title"]).replace('"', "'") + '"', s["no"],
            (s["grade"] or "-"), count_words(s["body"])))
    write(_MANI, "\n".join(rows) + "\n")

    # report
    n_pages = len(S) + 2  # sections + hub + index
    llms_kb = len(render_llms(S, D).encode("utf-8")) / 1024.0
    print("BUILT canonical site under docs/  (VP-SPEC v1.8)")
