# -*- coding: utf-8 -*-
"""
vp_ess_ac_condenser.py — ESS: 에어컨 실외기 폐열 회수 (정직한 100%-이하 회계)
==================================================================
사용자 구성: 에어컨 실외기(열 방출) → 모래 저장 → 검은구리 → 열전(직선) 변환.
질문: "100% 이하 맞지?" → 답: 맞다. *확실히, 큰 폭으로* 100% 이하다. 이를 수치로 보인다.

핵심 정직(반드시):
  · 에어컨은 실내 열 Q_c 를 퍼내며 전기 W 를 쓴다 → 실외기는 Q_h = Q_c + W 를 버린다.
  · 우리는 그 *버려지는 Q_h 의 일부* 만 열전으로 회수한다 (Carnot 한계, 저급열이라 1~2%).
  · ★회수 전기는 에어컨이 쓴 W 보다 *훨씬 작다*. 즉 에어컨을 공짜로 돌리는 게 아니다.
    (만약 회수 > W 라면 영구기관 — 불가능. 우리 수치는 그 한참 아래.)
  · 그래도 가치: 버리던 열의 회수(순이득) + 도시 열섬 완화 + 저장열 직접 사용(난방/온수).

이 모듈:
  [1] 에어컨 에너지수지 — Q_c, W, Q_h. 실외기가 버리는 열의 크기.
  [2] 열전 회수 — 실외기(고온) ↔ 냉각측. Carnot 한계 내 회수율.
  [3] ★100%-이하 회계 — 회수전기 vs 에어컨 입력 W. 과적(over-unity) 아님 증명.
  [4] 진짜 가치 — 열섬 완화 + 직접 열사용(전기 변환보다 훨씬 큼).

표준 라이브러리만·결정론·자체검증. 실행: python3 vp_ess_ac_condenser.py
"""
import math

T0 = 273.15

# 에어컨 (가정용 ~1RT) [CAL]
Q_COOL = 3.5         # 냉방 능력 Q_c [kW] (실내서 퍼내는 열)
COP_COOL = 3.5       # 냉방 성능계수 Q_c/W
T_COND = 50 + T0     # 실외기 응축 코일 온도 [K] (~50°C)
T_AMBIENT = 35 + T0  # 여름 외기 [K] (~35°C, 냉각측 후보 ①)
T_GROUND = 20 + T0   # 지중/야간복사 냉각측 [K] (~20°C, 냉각측 후보 ②)
ZT = 1.0             # 열전소재 [CAL]


def carnot(Th, Tc):
    return 1 - Tc / Th


def te_eff(Th, Tc, ZT):
    s = math.sqrt(1 + ZT)
    return carnot(Th, Tc) * (s - 1) / (s + Tc / Th)


def main():
    print("=" * 72)
    print("ESS — 에어컨 실외기 폐열 회수 (정직한 100%-이하 회계)")
    print("=" * 72)
    print("구성: 실외기 폐열 → 모래 저장 → 검은구리 → 열전(직선) 변환.")
    print("질문 '100% 이하 맞지?' → 답: 맞다, 큰 폭으로. 아래 수치로 증명.")

    # ── [1] 에어컨 에너지수지 ──
    print("\n" + "─" * 72)
    print("[1] 에어컨 에너지수지 — 실외기가 버리는 열 Q_h = Q_c + W [F]")
    print("─" * 72)
    W = Q_COOL / COP_COOL                 # 에어컨 전기 입력
    Q_h = Q_COOL + W                       # 실외기 방출열
    print(f"  냉방 Q_c = {Q_COOL:.1f} kW (실내서 퍼냄), 성능 COP = {COP_COOL:.1f}")
    print(f"  전기 입력 W = Q_c/COP = {W:.2f} kW")
    print(f"  실외기 방출열 Q_h = Q_c + W = {Q_h:.2f} kW  ← 이게 '버려지는 폐열' (현재 대기로)")
    print(f"  → 실외기는 들어간 전기 {W:.2f}kW 의 약 {Q_h/W:.1f}배 열을 버린다(실내열 포함).")
    assert abs(Q_h - (Q_COOL + W)) < 1e-9

    # ── [2] 열전 회수 ──
    print("\n" + "─" * 72)
    print("[2] 열전 회수 — 실외기(50°C) ↔ 냉각측, Carnot 한계 내 [F?]")
    print("─" * 72)
    print(f"  {'냉각측':<22}{'ΔT[K]':>7}{'Carnot':>9}{'열전ZT1':>9}{'회수전력[W]':>13}")
    for label, Tc in [("여름 외기 35°C", T_AMBIENT), ("지중/야간복사 20°C", T_GROUND)]:
        ec = carnot(T_COND, Tc); et = te_eff(T_COND, Tc, ZT)
        rec = et * Q_h * 1000             # 회수 전력 [W]
        print(f"  {label:<22}{T_COND-Tc:>7.0f}{ec*100:>8.1f}%{et*100:>8.1f}%{rec:>13.0f}")
    print("  → 여름엔 외기도 더워 ΔT 작음(회수 낮음). 냉각측을 지중/야간복사로 두면 개선.")
    print("    저급열이라 회수율 1~2%대 — 대부분의 Q_h 는 여전히 냉각측 폐열로 빠진다.")

    # ── [3] ★100%-이하 회계 (over-unity 아님) ──
    print("\n" + "─" * 72)
    print("[3] ★100%-이하 회계 — 회수전기 vs 에어컨 입력 W [F]")
    print("─" * 72)
    et = te_eff(T_COND, T_GROUND, ZT)     # 더 나은 냉각측 기준
    rec_kW = et * Q_h
    print(f"  (좋은 냉각측 20°C 기준) 회수 전기 = {et*100:.1f}% × {Q_h:.2f}kW = {rec_kW*1000:.0f} W")
    print(f"  에어컨이 쓴 전기 W = {W*1000:.0f} W")
    print(f"  회수 / 입력 = {rec_kW/W*100:.1f}%  ← 입력의 {rec_kW/W*100:.0f}%만 회수. 100% 한참 아래.")
    print(f"  회수 / 방출열 Q_h = {et*100:.1f}%  ← 버린 열의 {et*100:.0f}%만 전기로.")
    print("  ⇒ 결론: *확실히 100% 이하*. 에어컨 전기를 되찾는 게 아니라, 버린 열의 일부만 회수.")
    print("     회수 > W 라면 영구기관(불가) — 우리 수치는 그 한참 아래라 열역학 위반 없음. ✓")
    assert rec_kW < W, "회수가 입력 초과 — over-unity(불가)"
    assert rec_kW < Q_h, "회수가 방출열 초과 — 100% 위반"

    # ── [4] 진짜 가치 ──
    print("\n" + "─" * 72)
    print("[4] 진짜 가치 — 전기 변환보다 '열섬 완화 + 직접 열사용'이 더 크다 [F?]")
    print("─" * 72)
    print(f"  · 전기 회수는 작다(~{rec_kW*1000:.0f}W). 그러나 Q_h={Q_h:.1f}kW 를 *대기로 안 버리는* 것 자체가")
    print(f"    도시 열섬 완화 — 실외기 열이 거리를 데워 에어컨이 더 돌아가는 악순환을 끊는다.")
    print(f"  · 저장한 열을 *직접* 쓰면(난방·온수·건조) 변환손실 없이 Q_h 대부분 활용 가능 —")
    print(f"    열→전기(1~2%)보다 열→열(90%+)이 훨씬 효율적. 용도에 맞게 쓰는 게 핵심.")
    print(f"  · 도시 규모(수백만 실외기 여름 가동) 합산 시, 회수+열섬완화 효과는 실질적.")

    # ── 결론 + 등급 ──
    print("\n" + "=" * 72)
    print("결론 — 에어컨 실외기 폐열 ESS: 100% 이하 확실, 정직히 가치 있다")
    print(f"  ① 실외기는 Q_h={Q_h:.1f}kW 폐열 방출 (입력 W={W:.1f}kW 의 {Q_h/W:.1f}배)")
    print(f"  ② 열전 회수는 Carnot 한계로 1~2%대 (저급열·여름 작은 ΔT)")
    print(f"  ③ ★회수전기({rec_kW*1000:.0f}W) ≪ 에어컨 입력({W*1000:.0f}W) — over-unity 아님, 100% 한참 아래 ✓")
    print(f"  ④ 가장 큰 가치는 전기보다 *열섬 완화 + 직접 열사용*")
    print("-" * 72)
    print("등급: [F] 에너지수지·Carnot·100%-이하 회계 · [F?] 열전 회수·열섬/직접사용 가치 ·")
    print("      [CAL] COP·온도·ZT · (over-unity/영구기관 주장 없음 — 열역학 준수)")
    print("정직 고지: 사용자 직관('100% 이하') 정확. 버린 열의 일부 회수지 입력 회수가 아니다.")
    print("=" * 72)


if __name__ == "__main__":
    main()
