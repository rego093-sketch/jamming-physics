# -*- coding: utf-8 -*-
"""
vp_ess_thermoelectric.py — ESS 재시뮬레이션: 폐열 포집 + 열전(직선) 변환 (재현가능)
==================================================================
사용자 수정 지침 반영:
  · '회전 진폭 → 전기장'(구 제안서, 반증된 기구) 를 폐기.
  · 열 → 전기는 *전기적 직선운동* = 열전(Seebeck): 열기울기가 전하를 *종방향*으로 민다.
    (이는 구리 전도 그림 '전기 = 종방향 EM, 자유전자 바다 관통'과 정확히 일치 — 회전 아님.)
  · 열원 확장: 태양뿐 아니라 반도체·전산센터·열대·여름 *폐열* 을 검은구리로 포집(히트펌프).

정직한 핵심(반드시 명시):
  열 → 전기는 Carnot 에 묶인다. 변환분만 전기, 나머지는 *반드시* 냉각측으로 폐열 배출.
  따라서 "열이 100% 전기로만 나간다"는 열역학상 불가 — 실제 비율을 계산해 보인다.
  단, 폐열은 *어차피 버려지던 에너지* 이므로 몇 %라도 회수는 실질 가치(특히 대규모).

이 모듈:
  [1] 기구 교정 — Seebeck 직선 전하수송(V=S·ΔT), 회전 아님. (구리 종방향 전기와 동일.)
  [2] Carnot 천장 — 변환분만 전기, 폐열 배출은 필연.
  [3] 폐열원 표 — 반도체·전산센터·열대·여름, 각 Carnot + 열전 효율 + 회수전력.
  [4] 히트펌프 정직 — 열을 옮길 뿐 순에너지 창출 불가(영구기관 금지).
  [5] 단열 역설 — 저장엔 단열, 변환엔 냉각측(기울기) 필요. 둘 다 완벽은 모순.
  [6] 규모 — 전산센터 폐열 회수의 현실적 기여.

표준 라이브러리만·결정론·자체검증. 실행: python3 vp_ess_thermoelectric.py
"""
import math

T0 = 273.15                  # 0°C [K]

# 폐열원: (이름, 고온 T_h[°C], 냉각측 T_c[°C], 비고) [CAL]
SOURCES = [
    ("반도체 칩",      85, 25, "고밀도 발열, 현재 전량 폐기"),
    ("전산센터 냉각수", 60, 25, "데이터센터, GW급 폐열"),
    ("여름 집열(검은구리)", 70, 25, "태양+흑체흡수, 옥상"),
    ("열대 주간 대기",  35, 15, "대기↔야간복사냉각 기울기 필요"),
]
ZT_NOW = 1.0                 # 상용 열전소재 ZT [CAL]
ZT_LAB = 2.5                 # 연구 최고 열전소재 ZT [CAL]


def carnot(Th, Tc):
    """Carnot 효율 (절대온도)."""
    return 1 - Tc / Th


def te_efficiency(Th, Tc, ZT):
    """열전 변환 효율 η = η_Carnot·(√(1+ZT)−1)/(√(1+ZT)+Tc/Th). Carnot 의 일부."""
    s = math.sqrt(1 + ZT)
    return carnot(Th, Tc) * (s - 1) / (s + Tc / Th)


def main():
    print("=" * 72)
    print("ESS 재시뮬레이션 — 폐열 포집 + 열전(전기적 직선운동) 변환")
    print("=" * 72)
    print("교정: '회전 진폭→전기장'(반증) → 열전 Seebeck(전하의 종방향 직선 드리프트).")
    print("      구리 전도 그림(전기=종방향 EM)과 일치. 회전 아님.")

    # ── [1] 기구 교정: Seebeck 직선 전하수송 ──
    print("\n" + "─" * 72)
    print("[1] 기구 — Seebeck 직선 전하수송 (회전 아닌 종방향 전기) [V]/[F?]")
    print("─" * 72)
    S = 200e-6   # 열전 제벡계수 ~200 µV/K (대표값) [CAL]
    print(f"  열기울기 ΔT 가 전하를 *직선*으로 민다: 제벡 전압 V = S·ΔT (S≈{S*1e6:.0f}µV/K).")
    print(f"  {'ΔT[K]':>7}{'제벡전압 V[mV]':>16}")
    for dT in (20, 35, 60):
        print(f"  {dT:>7}{S*dT*1e3:>14.1f}")
    print("  → 전기장은 회전 진폭이 아니라 *열기울기 위 전하의 종방향 드리프트*에서 나온다.")
    print("    이는 구리편의 '전기=종방향 EM, 자유전자 바다 관통'과 같은 기구. 직선운동 맞음.")
    assert S * 60 * 1e3 > 0

    # ── [2] Carnot 천장 + 폐열 배출 필연 ──
    print("\n" + "─" * 72)
    print("[2] Carnot 천장 — 변환분만 전기, 나머지는 필연적 폐열 [F]")
    print("─" * 72)
    print("  열 → 전기는 단일 열원만으로는 불가(2법칙). *고온 ↔ 냉각측* 기울기가 있어야 한다.")
    print("  변환 상한 η_Carnot = 1 − T_c/T_h; 실제 열전은 그 일부. 나머지 (1−η)는 냉각측 폐열.")
    Th, Tc = 60 + T0, 25 + T0
    eta_c = carnot(Th, Tc); eta_te = te_efficiency(Th, Tc, ZT_NOW)
    print(f"  예) 60°C 열 1 kW 투입(전산센터): Carnot {eta_c*100:.1f}% / 열전(ZT=1) {eta_te*100:.1f}%")
    print(f"      → 전기 {eta_te*1000:.0f} W + 폐열 배출 {(1-eta_te)*1000:.0f} W. '100% 전기'는 불가.")
    print(f"  ⇒ 정직: 열은 '거의 전기로만' 못 나간다. 저급열일수록 대부분 폐열로 빠진다.")
    assert eta_te < eta_c < 1, "Carnot 위반"

    # ── [3] 폐열원 표 ──
    print("\n" + "─" * 72)
    print("[3] 폐열원별 회수 — 반도체·전산센터·여름·열대 [F?]/[CAL]")
    print("─" * 72)
    print(f"  {'열원':<16}{'T_h°C':>6}{'T_c°C':>6}{'Carnot':>8}{'열전ZT1':>8}{'열전ZT2.5':>9}")
    for name, th, tc, note in SOURCES:
        Th, Tc = th + T0, tc + T0
        ec = carnot(Th, Tc) * 100
        e1 = te_efficiency(Th, Tc, ZT_NOW) * 100
        e2 = te_efficiency(Th, Tc, ZT_LAB) * 100
        print(f"  {name:<16}{th:>6}{tc:>6}{ec:>7.1f}%{e1:>7.1f}%{e2:>8.1f}%")
    print("  → 저급 폐열은 효율 1~5%. 단위당 작지만 *열이 공짜(폐기예정)* 라 회수는 순이득.")
    print("    고온원(반도체 85°C)일수록 효율↑. 검은구리는 여기서 '포집(흡수)' 역할.")

    # ── [4] 히트펌프 정직 ──
    print("\n" + "─" * 72)
    print("[4] 히트펌프 정직 — 열을 옮길 뿐, 순에너지 창출 불가 [F]")
    print("─" * 72)
    Th_hp, Tc_hp = 60 + T0, 25 + T0
    COP_heat = Th_hp / (Th_hp - Tc_hp)     # 이상 히트펌프 난방 COP
    print(f"  히트펌프는 전기로 열을 저온→고온 이동. 난방 COP_ideal = T_h/(T_h−T_c) = {COP_heat:.1f}")
    print(f"  (전기 1 넣어 열 {COP_heat:.1f} 이동 — *열 이동*이지 전기 창출 아님.)")
    print(f"  ★발전엔 도움 안 됨: 펌프로 열 올려 다시 발전하면 넣은 전기보다 적게 나온다(영구기관 금지).")
    print(f"  올바른 용도: ① 저급 폐열을 난방/온수로 직접 활용(COP>1), ② 발전은 *기존 고온 폐열* 회수.")
    assert COP_heat > 1, "히트펌프 COP 계산 오류"

    # ── [5] 단열 역설 ──
    print("\n" + "─" * 72)
    print("[5] 단열 역설 — 저장엔 단열, 변환엔 냉각측 필요 [F]")
    print("─" * 72)
    print("  · 열을 *저장* 하려면 완벽 단열(손실 0)이 이상적.")
    print("  · 그러나 열을 *전기로 변환* 하려면 고온↔냉각측 *기울기* 가 필요 → 냉각측으로 열이 나가야 함.")
    print("  · 따라서 '완벽 단열 + 전기 변환'은 동시 불가: 단열로 가두면 기울기가 없어 변환도 0.")
    print("  → 작동 설계: 평소 단열로 저장 → 필요시 *제어된 열경로*를 열전으로 열어 냉각측과 연결,")
    print("    Carnot 한계 내 전기 생성(폐열 배출 동반). '전기로만 나간다'가 아니라 '유용출력=전기'.")

    # ── [6] 규모: 전산센터 폐열 ──
    print("\n" + "─" * 72)
    print("[6] 규모 — 전산센터 폐열 회수의 현실적 기여 [F?]/[CAL]")
    print("─" * 72)
    Th, Tc = 60 + T0, 25 + T0
    eta = te_efficiency(Th, Tc, ZT_NOW)
    DC_heat_MW = 30.0                      # 중형 데이터센터 폐열 [MW]
    rec_MW = DC_heat_MW * eta
    rec_GWh_yr = rec_MW * 8760 / 1000
    global_TWh = 450.0                     # 전세계 데이터센터 전력 ~연 450 TWh(≈전량 열) [CAL]
    global_rec = global_TWh * eta
    print(f"  중형 데이터센터 폐열 {DC_heat_MW:.0f} MW @60°C, 열전 ZT=1 ({eta*100:.1f}%):")
    print(f"    회수 전력 ≈ {rec_MW*1000:.0f} kW 연속 = {rec_GWh_yr:.1f} GWh/년 (어차피 버리던 열).")
    print(f"  전세계 데이터센터 ~{global_TWh:.0f} TWh/년(거의 전량 열) → {eta*100:.1f}% 회수 ≈ {global_rec:.0f} TWh/년.")
    print(f"  → 실질 기여(원전 ~{global_rec/8:.0f}기분). 단, '에너지 문제 탈출'은 과장 —")
    print(f"    이미 쓴 에너지의 *일부 회수*지 새 에너지 창출이 아니며, Carnot 가 상한을 둔다.")
    assert 0 < eta < 0.2, "저급열 효율이 비현실적"

    # ── 결론 + 등급 ──
    print("\n" + "=" * 72)
    print("결론 — 교정된 ESS: 열전(직선) 변환은 작동하나 Carnot 에 묶인다")
    print("  ① 기구 교정 옳음: 회전 진폭(반증) → Seebeck 직선 전하수송(구리 종방향 전기와 일치)")
    print("  ② 그러나 열→전기는 Carnot 한계: 저급 폐열 1~5%, 나머지는 폐열 배출(불가피)")
    print("  ③ 히트펌프는 열 이동일 뿐 순전력 창출 불가; 발전은 기존 고온 폐열 회수에 유효")
    print("  ④ 단열(저장)과 변환(냉각측 필요)은 동시 완벽 불가 — 제어된 열경로로 절충")
    print("  ⑤ 가치: 전산센터 등 폐열 회수는 대규모서 실질적(~수십 TWh/년) — 단 '문제 탈출'은 과장")
    print("-" * 72)
    print("등급: [F] Carnot 천장·폐열 배출·히트펌프 한계·단열 역설 ·")
    print("      [V]/[F?] Seebeck 직선수송·열전 효율 · [CAL] ZT·제벡계수·열원 온도·규모 ·")
    print("      [O]/폐기 구 '회전 진폭→전기장 81.7%'(반증; 열역학 한계 무시)")
    print("정직 고지: 교정 방향(직선 전기)은 옳다. 단 81.7% 같은 수치는 Carnot 가 금지한다.")
    print("  작동하는 설계는 한계를 인정하고 그 안에서 폐열을 회수한다 — 그게 진짜 가치다.")
    print("=" * 72)


if __name__ == "__main__":
    main()
