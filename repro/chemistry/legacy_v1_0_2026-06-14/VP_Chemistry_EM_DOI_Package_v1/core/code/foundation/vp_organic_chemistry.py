# -*- coding: utf-8 -*-
"""
vp_organic_chemistry.py — VP 유기화학: 탄소 골격과 혼성 (재현가능·인과적)
====================================================================
사용자 흐름: 무기·물리화학 → 유기화학. 탄소 골격 = 화학의 절반. 핵심 혼성(sp³/sp²/sp)이
      vp_molecular_geometry의 EM 반발 기하와 직결.

핵심: 탄소 4가(2s²2p²→4결합, vp_valence). 혼성 = σ영역 수 = VSEPR 기하(EM 1/r² 반발).
      4영역 sp³ 사면체 109.5°, 3영역 sp² 평면 120°, 2영역 sp 직선 180°.
      σ/π: 단일=1σ, 이중=1σ+1π, 삼중=1σ+2π → 결합차수 → 길이·세기.

인과 사슬: 탄소 원자가 4(껍질) → σ영역 수 → 혼성·기하(vp_molecular_geometry EM 반발) →
      탄소골격(사슬·고리·가지). 작용기=반응중심. 불포화도=(2C+2+N−H−X)/2.

등급: [F] 혼성 기하(VSEPR EM 반발)·결합차수-길이-세기·불포화도 (탄소골격 직접)
      [F?] 작용기 반응성 경향 · [O] 절대 반응속도·입체선택성(전이상태 구조)
실행: python3 vp_organic_chemistry.py   (표준 라이브러리만)
"""
import math

# 혼성: (σ영역, 기하, 각도, π수)
HYBRID = {
 "sp3": (4, "사면체",   109.47, 0),
 "sp2": (3, "삼각평면", 120.0,  1),
 "sp":  (2, "직선",     180.0,  2),
}
# C-C 결합차수: (길이pm, 세기kJ/mol)
CC_BOND = {1:(154,348), 2:(134,614), 3:(120,839)}
# 작용기
FUNC_GROUPS = [
 ("알케인",  "C–C",   "sp3", "단일결합, 비반응성(포화)"),
 ("알켄",    "C=C",   "sp2", "이중결합, 첨가반응"),
 ("알카인",  "C≡C",   "sp",  "삼중결합, 첨가반응"),
 ("알코올",  "–OH",   "sp3", "수소결합, 산화→알데하이드/케톤"),
 ("에터",    "C–O–C", "sp3", "비교적 비반응성"),
 ("알데하이드","–CHO", "sp2", "C=O, 산화/환원 둘 다"),
 ("케톤",    "C=O",   "sp2", "카보닐, 친핵성 첨가"),
 ("카복실산","–COOH", "sp2", "산성(양성자 내줌, vp_solution)"),
 ("아민",    "–NH2",  "sp3", "염기성(고립쌍, 양성자 받음)"),
 ("아마이드","–CONH–","sp2", "펩타이드 결합(단백질)"),
]

def unsaturation(C, H, N=0, X=0):
    """불포화도(고리+π) = (2C+2+N−H−X)/2."""
    return (2*C + 2 + N - H - X)//2


def main():
    print("="*72)
    print("VP 유기화학 — 탄소 골격과 혼성 (EM 기하 위에)")
    print("="*72)
    print("\n원리: 탄소 4가(껍질). 혼성=σ영역 수=VSEPR 기하(EM 1/r² 반발, vp_molecular_geometry).")

    # ── 혼성과 기하 ──
    print("\n[혼성과 기하] σ영역 수 → 혼성 → 기하 (EM 반발에서)")
    print(f"  {'혼성':<6}{'σ영역':>6}{'π수':>5}  {'기하':<10}{'각도':>8}  예")
    print("  "+"-"*46)
    examples = {"sp3":"CH₄ 메테인","sp2":"C₂H₄ 에틸렌","sp":"C₂H₂ 아세틸렌"}
    for h,(dom,geo,ang,npi) in HYBRID.items():
        print(f"  {h:<6}{dom:>6}{npi:>5}  {geo:<10}{ang:>7.1f}°  {examples[h]}")
    print("  → 사면체 109.47°=arccos(−1/3) (vp_molecular_geometry EM-sim과 동일값). [F]")
    print("    혼성은 σ영역 수가 정함. π는 영역 수 안 늘림(같은 방향). 탄소 4가에서.")

    # ── 결합차수 ──
    print("\n[σ/π 결합과 차수] 단일=1σ, 이중=1σ+1π, 삼중=1σ+2π")
    print(f"  {'결합':<8}{'차수':>5}  {'구성':<9}{'길이pm':>8}{'세기kJ':>8}")
    print("  "+"-"*40)
    for order,(L,E) in CC_BOND.items():
        comp = {1:"1σ",2:"1σ+1π",3:"1σ+2π"}[order]
        bond = {1:"C–C",2:"C=C",3:"C≡C"}[order]
        print(f"  {bond:<8}{order:>5}  {comp:<9}{L:>8}{E:>8}")
    print("  → 차수↑ → 길이↓·세기↑ (π 추가가 당김). 삼중(120pm)<이중<단일(154pm). [F]")
    print(f"    세기 비: C≡C/C–C = {839/348:.2f} (3중이 단일의 2.4배, 선형누적 아님).")

    # ── 불포화도 ──
    print("\n[불포화도] 고리+π = (2C+2+N−H−X)/2 (분자식에서 구조 추론)")
    print(f"  {'분자':<14}{'식':<12}{'불포화도':>9}  의미")
    print("  "+"-"*44)
    mols = [("에테인","C₂H₆",2,6,0,0,"포화(0)"),("에틸렌","C₂H₄",2,4,0,0,"이중1"),
            ("아세틸렌","C₂H₂",2,2,0,0,"삼중(=2)"),("벤젠","C₆H₆",6,6,0,0,"고리1+π3=4"),
            ("사이클로헥세인","C₆H₁₂",6,12,0,0,"고리1")]
    for name,formula,C,H,N,X,meaning in mols:
        u = unsaturation(C,H,N,X)
        print(f"  {name:<14}{formula:<12}{u:>9}  {meaning}")
    print("  → 분자식만으로 고리·π 개수 = 불포화도. 벤젠 4(고리1+이중3). [F]")

    # ── 작용기 ──
    print("\n[작용기] 반응 중심 — 탄소골격에 붙은 반응성 부위")
    print(f"  {'작용기':<10}{'구조':<8}{'혼성':<6} 반응성")
    print("  "+"-"*50)
    for name,struct,hyb,react in FUNC_GROUPS:
        print(f"  {name:<10}{struct:<8}{hyb:<6} {react}")
    print("  → 작용기가 유기분자 반응성 결정. 카복실산=산(vp_solution), 아민=염기. [F?]")

    # ── 이성질체 ──
    print("\n[이성질체] 같은 분자식, 다른 구조 (탄소골격의 다양성)")
    print("  • 구조이성질체: C₄H₁₀ = 뷰테인/아이소뷰테인 (사슬 vs 가지).")
    print("  • 입체이성질체: 사면체 탄소 4개 다른 치환기 → 거울상(키랄성).")
    print("  → 탄소 4가+사면체(EM 기하)가 이성질체·키랄성의 기하적 기원. [F]")

    # ── VP 통일 ──
    print("\n[VP 통일] 탄소 골격이 EM 기하 위에")
    print("  • 탄소 4가(껍질, vp_valence) → σ영역 수 → 혼성·기하(EM 반발, vp_molecular_geometry).")
    print("  • 사면체 109.47°=arccos(−1/3): 무기·유기 공통 EM-sim 결과. 탄소화학의 기하 토대.")
    print("  • 작용기 반응성: 산염기(vp_solution)·산화환원(vp_electrochem)·속도(vp_kinetics) 적용.")
    print("  • 생명 분자(단백질 아마이드, 당, 지질)도 같은 4가·사면체·작용기 위에.")

    print("\n" + "="*72)
    print("등급: [F] 혼성 기하(VSEPR EM 반발)·결합차수-길이-세기·불포화도·키랄성")
    print("      [F?] 작용기 반응성 경향 · [O] 절대 반응속도·입체선택성")
    print("      핵심: 탄소골격이 EM 기하 위에. 혼성=σ영역=VSEPR, 사면체 arccos(−1/3).")
    print("="*72)


if __name__ == "__main__":
    main()
