# -*- coding: utf-8 -*-
"""
vp_thermal.py — VP 열역학 = 회전에너지 (재현가능·인과적)
====================================================================
주장: 열역학은 회전에너지로 본다. VP에서 입자·격자는 본질적으로 회전(전자=회전 덴트).
      열에너지 = 재밍된 격자 원자의 회전·진동 들뜸. 온도 = 자유도당 회전에너지.
      (앞서 온도=자유도당E 일부 정리 — 여기서 완성.)

인과 사슬: 회전·진동 자유도 = 2차 자유도 → 등분배 각 (1/2)kT → 열용량 = (자유도/2)R.
           분자 회전 E_J=B·J(J+1), B=ℏ²/2I, I=μr²(VP 결합길이·질량) → 회전상수 예측.
           엔트로피 S=k lnΩ (Ω=회전 위상공간 미시상태수).

등급: [F] 열용량 DOF 계수(등분배, 단원자 3/2R·이원자 5/2R·고체 3R) ·
      [F] 회전상수 B(VP 결합길이+질량, <2%) · [개념] 엔트로피=회전위상공간.
실행: python3 vp_thermal.py   (표준 라이브러리만)
"""
import math
PI = math.pi
R   = 8.314462         # 기체상수 [J/mol·K]
KB  = 1.380649e-23     # 볼츠만 [J/K]
H   = 6.62607015e-34   # 플랑크 [J·s]
HBAR= H/(2*PI)
C_CM= 2.99792458e10    # 빛속도 [cm/s]
U_KG= 1.66053907e-27   # 원자질량단위 [kg]


def heat_capacity_dof(dof):
    """등분배: 2차 자유도 dof개 → C = (dof/2)·R [J/mol·K]."""
    return dof/2 * R

def rotational_constant(m1_u, m2_u, r_pm):
    """이원자 회전상수 B [cm⁻¹] = ℏ²/2I, I=μr².  (VP 결합길이·질량)"""
    mu = (m1_u*m2_u/(m1_u+m2_u)) * U_KG       # 환산질량 [kg]
    I  = mu * (r_pm*1e-12)**2                  # 관성모멘트 [kg·m²]
    B_J = HBAR**2/(2*I)                         # [J]
    return B_J/(H*C_CM)                         # → [cm⁻¹]


def main():
    print("="*72)
    print("VP 열역학 = 회전에너지 — 열은 재밍격자의 회전·진동 들뜸")
    print("="*72)
    print("\n원리: 입자·격자는 회전(전자=회전 덴트). 열에너지 = 회전·진동 들뜸.")
    print("      온도 = 자유도당 회전에너지. 각 2차 자유도 = (1/2)kT (등분배).")

    # ── 열용량 = 자유도 계수 ──
    print("\n[열용량] = 회전·진동·병진 자유도 계수 (등분배) — 실측 대조")
    print(f"  {'계':<14}{'자유도(2차)':<22}{'C예측':>8}{'C실측':>8}{'단위 J/mol·K'}")
    print("  "+"-"*58)
    systems = [
        ("단원자 기체", "병진 3",                3, 12.5,  "He·Ne·Ar"),
        ("이원자 기체", "병진 3+회전 2",          5, 20.8,  "N2·O2·H2"),
        ("이원자(고온)", "병진3+회전2+진동2",      7, 29.1,  "고온 N2"),
        ("고체(뒬롱-프티)","진동 3모드×2(운동+위치)",6, 24.9,  "Cu·Al·Fe·Pb"),
    ]
    for name, dofdesc, dof, meas, ex in systems:
        c = heat_capacity_dof(dof)
        d = (c-meas)/meas*100
        print(f"  {name:<14}{dofdesc:<22}{c:>8.1f}{meas:>8.1f}   Δ={d:+.1f}% ({ex})")
    print("  → 열용량이 자유도 계수에서 직접. 회전 모드가 열어주는 자유도가 보인다. [F]")

    # ── 고체 뒬롱-프티 상세 ──
    print("\n[고체 뒬롱-프티] 원자당 진동 3모드, 각 운동+위치 = 2×(1/2)kT → 3R")
    metals = [("Cu",24.4),("Al",24.2),("Fe",25.1),("Pb",26.4),("Au",25.4)]
    dp = heat_capacity_dof(6)
    print(f"  뒬롱-프티 예측 C = 3R = {dp:.1f} J/mol·K  (고온 극한)")
    for sym, meas in metals:
        print(f"    {sym:<4} 실측 {meas:.1f}  Δ={(dp-meas)/meas*100:+.1f}%")
    print("  → 재밍격자 원자가 3차원 진동(회전 들뜸의 격자판) → 3R. 저온은 양자 동결(Debye [O]).")

    # ── 회전 에너지 준위 (분자 회전) ──
    print("\n[회전 에너지 준위] 분자 회전 E_J=B·J(J+1), B=ℏ²/2I (VP 결합길이+질량)")
    print(f"  {'분자':<6}{'질량1':>6}{'질량2':>6}{'결합[pm]':>9}{'B예측':>8}{'B실측':>8}{'[cm⁻¹]'}")
    print("  "+"-"*52)
    mols = [("H2",1.008,1.008,74.1,60.8),("N2",14.003,14.003,109.8,2.00),
            ("CO",12.0,15.995,112.8,1.93),("HCl",1.008,34.969,127.5,10.59),
            ("O2",15.995,15.995,120.8,1.45)]
    errs=[]
    for name,m1,m2,r,Bm in mols:
        B = rotational_constant(m1,m2,r)
        d=(B-Bm)/Bm*100; errs.append(abs(d))
        print(f"  {name:<6}{m1:>6.1f}{m2:>6.1f}{r:>9.1f}{B:>8.2f}{Bm:>8.2f}   Δ={d:+.1f}%")
    print(f"  평균오차 {sum(errs)/len(errs):.1f}%. → 회전상수가 VP 결합길이·질량에서 직접. [F]")

    # ── 회전-진동 자유도 활성화 ──
    print("\n[자유도 활성화] 회전·진동 모드는 kT > 준위간격일 때 깨어난다")
    print("  • 저온: 병진만 (회전 동결) → C=(3/2)R")
    print("  • 상온: 회전 활성(B~수 cm⁻¹ ≪ kT~200cm⁻¹) → 이원자 C=(5/2)R")
    print("  • 고온: 진동도 활성(ℏω~수백~수천 cm⁻¹) → C→(7/2)R")
    print("  → 회전준위 간격(VP 기하)이 어느 온도에서 모드가 열리는지 정한다.")

    # ── 엔트로피·온도·기체법칙 (회전 위상공간) ──
    print("\n[엔트로피·온도] 회전 위상공간으로")
    print("  • 온도 T = 자유도당 회전·진동 에너지 (E_dof = (1/2)kT).")
    print("  • 엔트로피 S = k·lnΩ, Ω = 접근가능한 회전·진동 미시상태수.")
    print("    가열 → 회전 위상공간 팽창 → Ω↑ → S↑ (2법칙=회전위상공간 확산).")
    print("  • 기체법칙 PV=nRT: 압력 = 회전·병진 운동량 전달률, T = 그 에너지 척도.")

    # ── VP 통일 ──
    print("\n[VP 통일] 회전이 열을 낳는다")
    print("  • 전자 = 회전 덴트(r_vac=D/2π²). 입자의 근본이 회전.")
    print("  • 열 = 그 회전·진동의 거시적 들뜸. 온도 = 자유도당 회전에너지.")
    print("  • 재밍격자(고체)의 진동 3R, 분자 회전 B, 기체 병진 — 모두 회전에너지의 갈래.")

    print("\n" + "="*72)
    print("등급: [F] 열용량 DOF 계수(단원자3/2R·이원자5/2R·고체3R) · [F] 회전상수 B(<2%)")
    print("      [개념] 엔트로피=회전위상공간·온도=자유도당회전E · [O] 저온 양자열용량(Debye)")
    print("      핵심: 열역학 = 회전에너지. 온도·열용량·회전준위가 VP 회전 위에 선다.")
    print("="*72)


if __name__ == "__main__":
    main()
