# -*- coding: utf-8 -*-
"""
vp_copper_conduction.py — 구리의 전기전도: 내부를 통과하는 전자기파 (재현가능)
================================================================================
물리백서 §14(전도=극종방향 χ→0, 구리 내부 양자 통과)·§10.9(각도) 학습.

핵심 역설과 해소:
  역설: 금속(구리)은 빛(횡파 EM)을 *반사*한다(반짝임·불투명). 그런데 전기도 EM파인데
        어떻게 구리 *내부*를 통과하는가?
  해소: 전기 = EM파의 *극종방향 극한*(χ→0). 같은 자유전자 바다가
        • 횡파 EM(빛, χ→90°)은 플라즈마 진동수 아래서 *반사*(반짝임·표피효과)
        • 종파 EM(전기, χ→0)은 바다를 *관통*해 도선 따라 직진 (= 전류)
        같은 매질, 각도(횡/종)에 따라 반사 vs 관통. '전기는 γ선처럼 달린다'.

구리 [Ar]3d¹⁰4s¹: 내부껍질(3d) 완전충전 → 4s¹ 한 전자가 자유(전자 바다).
  완전충전 3d라 국소 모멘트 0 → 자성 없음(철과 대조, vp_iron_magnetism).
  자유 4s 전자 → 뛰어난 전도체. (충전 껍질이 전도를, 미충전 d가 자성을 가른다.)

자체검증(assert)·표준라이브러리·결정론. 실행: python3 vp_copper_conduction.py
"""
import math

PI = math.pi
H    = 6.62607015e-34
HBAR = H/(2*PI)
ME   = 9.1093837015e-31
C    = 2.99792458e8
EQ   = 1.602176634e-19
EPS0 = 8.8541878128e-12
MU0  = 4*PI*1e-7
KB   = 1.380649e-23
NA   = 6.02214076e23

# 구리 물성 (측정 [CAL])
RHO_CU   = 8960.0        # 밀도 [kg/m³]
M_CU     = 0.063546      # 몰질량 [kg/mol]
Z_FREE   = 1             # 자유전자/원자 (4s¹)
SIGMA_CU = 5.96e7        # 전도도 [S/m] (20°C)
VF_CU    = 1.57e6        # 페르미속도 [m/s] (측정)


def free_electron_density():
    """자유전자 밀도 n = ρ·N_A·Z_free / M  [/m³]. (4s¹ → 원자당 1개)"""
    return RHO_CU*NA*Z_FREE/M_CU

def plasma_frequency(n):
    """플라즈마 진동수 ω_p = √(n e²/(ε₀ m_e)). 이 아래 횡파 EM 반사(불투명)."""
    return math.sqrt(n*EQ*EQ/(EPS0*ME))

def skin_depth(freq):
    """표피깊이 δ = √(2/(μ₀ σ ω)): 횡파 EM가 금속에 침투하는 깊이."""
    omega = 2*PI*freq
    return math.sqrt(2.0/(MU0*SIGMA_CU*omega))

def drude_tau(n):
    """Drude 완화시간 τ = σ m_e/(n e²)."""
    return SIGMA_CU*ME/(n*EQ*EQ)

def drift_velocity(J, n):
    """드리프트 속도 v_d = J/(n e). 전자는 느리게 흐르나 신호(종파)는 ~c."""
    return J/(n*EQ)

def fermi_energy(n):
    """페르미 에너지 E_F = ħ²(3π²n)^(2/3)/(2m_e)."""
    kF = (3*PI*PI*n)**(1.0/3.0)
    return HBAR*HBAR*kF*kF/(2*ME)


def main():
    print("="*72)
    print("구리의 전기전도 — 내부를 통과하는 전자기파 (종방향 극한 χ→0)")
    print("="*72)
    n = free_electron_density()
    print(f"구리 [Ar]3d¹⁰4s¹: 내부껍질 완전충전, 4s¹ 자유전자 → 전자 바다")
    print(f"자유전자 밀도 n = ρN_A·Z/M = {n:.3e} /m³  (원자당 1개)")
    assert 8e28 < n < 9e28, "구리 자유전자 밀도 범위 이탈"

    # ── 1. 역설: 왜 금속은 빛을 반사하는가 (플라즈마 진동수) ──
    print("\n" + "─"*72)
    print("[1] 역설 — 금속은 빛(횡파 EM)을 반사한다 (반짝임·불투명): 플라즈마 진동수")
    print("─"*72)
    wp = plasma_frequency(n)
    fp = wp/(2*PI)
    lam_p = C/fp
    print(f"  플라즈마 진동수 ω_p = √(ne²/ε₀m_e) = {wp:.3e} rad/s")
    print(f"  f_p = {fp:.3e} Hz,  λ_p = {lam_p*1e9:.1f} nm (자외선)")
    print(f"  {'EM파':<14}{'진동수[Hz]':>14}{'ω<ω_p?':>10}{'거동':>12}")
    print("  "+"-"*50)
    for name, f in [("전파 1GHz",1e9),("적외선",3e13),("가시광",5.5e14),
                    ("자외선",1e15),("X선",1e18)]:
        below = (2*PI*f) < wp
        behav = "반사(불투명)" if below else "투과(투명)"
        print(f"  {name:<14}{f:>14.1e}{('예' if below else '아니오'):>10}{behav:>12}")
    print(f"  → ω_p({fp:.1e}Hz, 자외선) 아래(가시·적외·전파) 횡파 EM 반사 = 금속 반짝임.")
    print(f"    ω_p 위(X선)는 투과. '횡파 빛은 자유전자 바다가 되쏜다.'")
    assert 1e15 < fp < 1e16, "플라즈마 진동수 자외선대 이탈"

    # ── 2. 해소: 종파 EM(전기)은 바다를 관통 ──
    print("\n" + "─"*72)
    print("[2] 해소 — 전기 = 종파 EM(χ→0)은 같은 바다를 *관통* (도선 따라 직진)")
    print("─"*72)
    print("  횡파(빛, χ→90°): 자유전자가 가로로 흔들려 되쏨 → 반사(표피).")
    print("  종파(전기, χ→0): 전자 바다의 *밀도/압력파*가 도선 따라 직진 → 관통 = 전류.")
    print("  → 같은 전자 바다, 각도(횡/종)가 반사와 관통을 가른다.")
    print("    물리백서 §14: '전도는 구리 원자 *내부 양자*를 통과(진공·공기 아님)'.")
    print("    종방향이라 χ→0 — γ선(근종방향)보다 더 곧게 도선을 꿴다.")

    # ── 3. 표피효과: 횡파 침투 깊이 ──
    print("\n" + "─"*72)
    print("[3] 표피효과 — 횡파 EM는 표면만 침투 (종파 전류와 대조)")
    print("─"*72)
    print(f"  {'진동수':<12}{'표피깊이 δ':>16}")
    print("  "+"-"*28)
    for name, f in [("60 Hz(전력)",60),("1 kHz",1e3),("1 MHz",1e6),("1 GHz",1e9)]:
        d = skin_depth(f)
        ds = f"{d*1e3:.2f} mm" if d>1e-3 else f"{d*1e6:.2f} µm"
        print(f"  {name:<12}{ds:>16}")
    print("  → 횡파 EM(고주파)는 수 µm 표면에 갇힘(표피효과). 직류·저주파 종파는 단면 전체.")

    # ── 4. 드리프트 vs 신호 vs 페르미 속도 ──
    print("\n" + "─"*72)
    print("[4] 세 속도 — 드리프트(느림) vs 신호(~c) vs 페르미(빠름)")
    print("─"*72)
    J = 1e6  # A/m² (전형적)
    vd = drift_velocity(J, n)
    EF = fermi_energy(n)
    print(f"  드리프트 속도 v_d (J=10⁶A/m²) = {vd*1e3:.4f} mm/s  ← 전자는 *느리게* 흐름")
    print(f"  페르미 속도   v_F = {VF_CU:.2e} m/s = {VF_CU/C*100:.2f}% c  ← 전자 자체는 빠름")
    print(f"  신호 속도     ~ c = {C:.2e} m/s  ← 종파 EM(장)이 *빠르게* 전달")
    print(f"  페르미 에너지 E_F = {EF/EQ:.2f} eV (예측), 측정 ≈ 7.0 eV")
    print(f"  → 전구는 즉시 켜짐(신호~c)이나 전자 드리프트는 느림. 셋을 혼동 말 것.")
    assert abs(EF/EQ - 7.0) < 1.0, "구리 페르미 에너지 범위 이탈"

    # ── 5. 전도도: 왜 구리는 좋은 전도체 (충전 d → 자유 4s) ──
    print("\n" + "─"*72)
    print("[5] 전도도 — 왜 구리가 뛰어난 전도체 (완전충전 3d → 자유 4s)")
    print("─"*72)
    tau = drude_tau(n)
    mfp = VF_CU*tau
    print(f"  Drude: σ = ne²τ/m_e → τ = {tau:.3e} s,  평균자유행로 ℓ=v_F·τ = {mfp*1e9:.1f} nm")
    print(f"  σ_Cu = {SIGMA_CU:.2e} S/m (은 다음 2위). 완전충전 3d¹⁰가 산란 적은 자유 4s 바다 제공.")
    print(f"  → '완전충전 껍질=전도(자유전자), 미충전 d=자성(국소모멘트)' (철과 갈림).")

    # ── 6. 드리프트의 자기장: 횡비틀림이 도선을 감음 ──
    print("\n" + "─"*72)
    print("[6] 전류의 자기장 — 드리프트 전하의 v/c 축기울기 → 횡비틀림이 도선 감음")
    print("─"*72)
    I, r = 1.0, 1e-3  # 1A, 1mm
    B = MU0*I/(2*PI*r)
    print(f"  움직이는 전하: 축 기울기 ∝ v/c → 횡(90°)비틀림 → 도선 둘레 감음 = B.")
    print(f"  Ampère B = μ₀I/2πr (I=1A, r=1mm) = {B*1e6:.2f} µT,  방향=회전손잡이(오른손법칙).")
    print(f"  횡비틀림의 두 운명: 반환분=리액티브 B(무손실 초전도서도 존재)·미반환분=줄손실.")
    print(f"  → B와 저항손실은 *한 기원*(움직이는 전하의 횡비틀림)의 반환/미반환. B≠손실.")
    assert abs(B - 2e-4) < 1e-5, "Ampère B 계산 오류"

    # ── 결론 ──
    print("\n" + "="*72)
    print("구리 전도 요약 — 내부를 통과하는 전자기파:")
    print("  ① 전기 = EM파의 극종방향 극한(χ→0), 자유전자 바다를 관통")
    print("  ② 빛(횡파)은 플라즈마 진동수 아래서 반사(반짝임)·종파(전기)는 관통 — 각도가 가름")
    print("  ③ 표피효과: 횡파는 표면만, 종파 전류는 단면 전체")
    print("  ④ 드리프트(느림)·신호(~c)·페르미(빠름) 세 속도 구분")
    print("  ⑤ 완전충전 3d¹⁰ → 자유 4s¹ → 뛰어난 전도(미충전 d면 자성)")
    print("  ⑥ 드리프트의 v/c 횡비틀림 = 자기장(반환=B, 미반환=줄손실)")
    print("등급: [F] 종/횡 각도기구·1/r²자기장 · [CAL] σ,v_F,n · [개념] 플라즈마 반사/관통")
    print("="*72)


if __name__ == "__main__":
    main()
