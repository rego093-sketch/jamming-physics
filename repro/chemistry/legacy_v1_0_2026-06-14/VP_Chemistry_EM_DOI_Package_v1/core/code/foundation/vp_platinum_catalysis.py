# -*- coding: utf-8 -*-
"""
vp_platinum_catalysis.py — 백금 촉매 기능: 전자 진폭 파장 공명 + 물 정수 응용 (재현가능)
========================================================================================
빛/EM 장·d블록·결정장 위에 섭니다. 응용백서(DOI 18043066: Pt 촉매/수전해/정수) 연계.

질문(사용자): 백금이 왜 뛰어난 촉매인가? '전자 진폭 파장'으로 촉매 기능을 분석하고
            물 정수(전기분해·수소)에 활용 가능성을 보라.

세 층위로 분석:
  [확립] Sabatier 원리 / 화산형(volcano): 촉매는 흡착이 *중간 세기*일 때 최적.
         Pt는 수소흡착 ΔG_H≈0(최적점) → HER(수소발생) 교환전류 최대.
  [확립] d-밴드 중심 모형: 활성은 d-밴드중심 ε_d 위치와 상관. Pt 최적 부근.
  [VP가설] 전자 진폭 파장 공명: 촉매 활성전자의 de Broglie 파장 λ_e가 표면
         기하(Pt-Pt 간격·흡착결합)와 *정합*하면 반결합궤도로의 역공여가 공명증폭
         → 결합 약화 → 촉매. Pt의 일함수·격자가 이 공명창에 듦. [H]

물 정수 응용: Pt 음극 HER(2H⁺+2e⁻→H₂) 과전압≈0 → 효율적 수전해 → 청정수소 +
            전기분해 살균/정수. 인가전위로 λ_e 조율 가능(공명 튜닝) = 전극설계 지렛대.

자체검증(assert)·표준라이브러리·결정론. 실행: python3 vp_platinum_catalysis.py
"""
import math

H    = 6.62607015e-34
HBAR = H/(2*math.pi)
ME   = 9.1093837015e-31
C    = 2.99792458e8
EV   = 1.602176634e-19
F    = 96485.33212        # 패러데이 상수 [C/mol]

# Pt 물성 [CAL]
PHI_PT   = 5.65       # 일함수 [eV]
A_PT     = 3.92e-10   # FCC 격자상수 [m]
D_PTPT   = A_PT/math.sqrt(2)   # 최근접 Pt-Pt [m] = 2.77 Å

# 결합/흡착 길이 [Å] (참조)
BONDS = {"H–H": 0.74, "O–H": 0.96, "O=O": 1.21, "Pt–H(표면)": 1.70, "Pt–Pt": D_PTPT*1e10}


def de_broglie(E_eV):
    """전자 진폭 파장(de Broglie) λ_e = h/√(2 m_e E) [Å]. E는 활성전자 에너지."""
    return H/math.sqrt(2*ME*E_eV*EV)*1e10


def main():
    print("="*72)
    print("백금 촉매 기능 — 전자 진폭 파장 공명 + 물 정수 응용")
    print("="*72)
    print("Pt [Xe]4f¹⁴5d⁹6s¹: 5d에 1개 빈자리(hole) → 페르미준위에 d-상태 →")
    print("  흡착물에 줄(공여)·받을(역공여) 전자가 항상 준비된 금속 촉매 (Au는 5d꽉참→불활성).")

    # ── 1. Sabatier / 화산형 (HER) ──
    print("\n" + "─"*72)
    print("[1] Sabatier 원리 / 화산형 — 흡착 중간세기가 최적, Pt가 정점 (수소발생 HER)")
    print("─"*72)
    print("  원리: 너무 약하면 활성화 못함, 너무 강하면 생성물 못 떼냄(피독). ΔG_ads≈0 최적.")
    print(f"  {'금속':<6}{'ΔG_H[eV]':>10}{'log₁₀j₀[A/cm²]':>16}{'평가':>12}")
    print("  "+"-"*44)
    # (금속, ΔG_H, log10 교환전류밀도) [CAL]
    her = [("Pt",-0.09,-3.1),("Ir",-0.10,-3.7),("Pd",-0.20,-3.5),("Rh",-0.28,-3.6),
           ("Ni",-0.28,-5.2),("Au",0.30,-5.4),("W",-0.55,-5.9),("Mo",-0.55,-6.3),
           ("Hg",0.50,-12.6)]
    best = max(her, key=lambda x: x[2])
    for m, dg, lj in her:
        tag = "← 정점(최적)" if m == best[0] else ("너무강" if dg < -0.4 else "너무약" if dg > 0.2 else "양호")
        print(f"  {m:<6}{dg:>10.2f}{lj:>16.1f}{tag:>12}")
    print(f"  → Pt: ΔG_H={best[1]}eV(0에 최근접) → 교환전류 최대(log j₀={best[2]}). 화산 정점.")
    print("    너무강(W·Mo): 수소 못떼냄. 너무약(Au·Hg): 활성화 못함. Pt가 균형점.")
    assert best[0] == "Pt", "HER 화산 정점이 Pt 아님"
    assert abs(-0.09) < 0.15, "Pt ΔG_H 최적범위 이탈"

    # ── 2. d-밴드 중심 ──
    print("\n" + "─"*72)
    print("[2] d-밴드 중심 모형 — 활성 ∝ ε_d 위치 (Pt 최적 부근)")
    print("─"*72)
    print(f"  {'금속':<6}{'ε_d[eV]':>9}{'흡착세기':>12}")
    print("  "+"-"*27)
    # d-밴드 중심 (Hammer-Nørskov 근사) [CAL]
    eps_d = [("Ni",-1.29),("Pd",-1.83),("Rh",-1.73),("Ir",-2.11),("Pt",-2.25),
             ("Cu",-2.67),("Au",-3.56),("Ag",-4.30)]
    for m, e in eps_d:
        strength = "강(반응성↑)" if e > -2.0 else "약(귀금속)" if e < -3.0 else "중(최적권)"
        print(f"  {m:<6}{e:>9.2f}{strength:>12}")
    print("  → ε_d 높으면(페르미 근접) 강결합, 낮으면 약결합. Pt(-2.25)는 중간=최적권.")
    print("    Au(-3.56)는 너무 낮아 약결합(불활성), 초기TM은 너무 높아 강결합(피독).")

    # ── 3. 전자 진폭 파장 공명 (VP 가설) ──
    print("\n" + "─"*72)
    print("[3] 전자 진폭 파장 공명 (VP 가설) — λ_e가 표면 기하와 정합 → 역공여 공명")
    print("─"*72)
    lam_phi = de_broglie(PHI_PT)
    print(f"  활성전자 진폭 파장 λ_e = h/√(2m_eφ), φ={PHI_PT}eV → λ_e = {lam_phi:.2f} Å")
    print(f"  반파장 λ_e/2 = {lam_phi/2:.2f} Å  vs  Pt-Pt 최근접 = {D_PTPT*1e10:.2f} Å")
    ratio = (lam_phi/2)/(D_PTPT*1e10)
    print(f"  정합비 (λ_e/2)/(Pt-Pt) = {ratio:.3f}  → 반파장이 표면 한 칸에 ~정합(공명).")
    print(f"  {'에너지 E[eV]':<14}{'λ_e[Å]':>9}{'λ_e/2[Å]':>10}{'정합 대상':>16}")
    print("  "+"-"*49)
    for E, why in [(PHI_PT,"일함수(흡착)"),(2.25,"d-밴드중심"),(13.6,"수소 결합E"),(1.0,"저에너지")]:
        le = de_broglie(E)
        # 가장 가까운 결합 찾기
        target = min(BONDS.items(), key=lambda kv: abs(le/2 - kv[1]))
        print(f"  {E:<14.2f}{le:>9.2f}{le/2:>10.2f}{target[0]+f'({target[1]:.2f}Å)':>16}")
    print("  → 가설: λ_e/2가 흡착 기하(Pt-Pt·Pt-H)와 정합할 때, 활성전자가 흡착물")
    print("    반결합궤도에 *공명 역공여* → 결합 약화 → 촉매. Pt 일함수·격자가 공명창. [H]")
    print(f"  검증: 일함수 전자 반파장 {lam_phi/2:.2f}Å ≈ Pt-Pt {D_PTPT*1e10:.2f}Å (정합비 {ratio:.2f}).")
    assert 0.8 < ratio < 1.2, "전자 진폭 파장-격자 정합 창 이탈"

    # ── 4. 공명 튜닝: 인가전위로 λ_e 조율 (전기분해 지렛대) ──
    print("\n" + "─"*72)
    print("[4] 공명 튜닝 — 인가전위가 활성전자 에너지를 옮겨 λ_e 조율 (전기분해 지렛대)")
    print("─"*72)
    print(f"  {'인가전위 V':<12}{'유효E[eV]':>10}{'λ_e[Å]':>9}{'λ_e/2[Å]':>10}")
    print("  "+"-"*41)
    for V in [-0.5, 0.0, 0.5, 1.23]:
        Eeff = PHI_PT - V        # 음극분극(−V)서 전자에너지↑ → λ_e↑ (개략)
        if Eeff <= 0: continue
        le = de_broglie(Eeff)
        print(f"  {V:<12.2f}{Eeff:>10.2f}{le:>9.2f}{le/2:>10.2f}")
    print("  → 인가전위로 λ_e를 옮겨 공명창 조율 가능. 1.23V=물분해 이론전압.")
    print("    즉 전극 전위가 '전자 진폭 파장 공명'의 튜닝 손잡이 = 수전해 전극설계 지렛대. [H]")

    # ── 5. 물 정수 응용: HER 수전해 + 살균/정수 ──
    print("\n" + "─"*72)
    print("[5] 물 정수 응용 — Pt 음극 HER 수전해(청정수소) + 전기분해 살균/정수")
    print("─"*72)
    print("  물 전기분해: 음극 2H₂O+2e⁻→H₂+2OH⁻ (HER, Pt 촉매), 양극 산화(O₂/산화제).")
    print(f"  열역학 분해전압 = 1.23 V. Pt HER 과전압 ≈ 30 mV(거의 0) → 음극 손실 최소.")
    eta_pt = 0.03; eta_ni = 0.30
    print(f"  과전압 비교: Pt η≈{eta_pt*1000:.0f}mV vs Ni η≈{eta_ni*1000:.0f}mV → Pt가 에너지 효율↑.")
    # 수소 생산 패러데이: 1A·s → mol H2
    I, t = 1.0, 3600.0   # 1A 1시간
    mol_H2 = I*t/(2*F)
    L_H2 = mol_H2*22.414  # STP
    print(f"  생산: 1A·1h → H₂ {mol_H2*1000:.2f} mmol = {L_H2*1000:.1f} mL(STP) (n=2 패러데이).")
    print("  정수 효과: (i) 전기분해가 미생물·유기물 산화분해(살균), (ii) 발생 H₂/활성종이")
    print("    오염물 환원, (iii) 응용백서 EM/전기장 탈염과 결합 → 통합 정수.")
    print("  → Pt 촉매 효율(전자 진폭 파장 공명)이 저전압 수전해·정수를 가능케 함.")
    assert abs(mol_H2 - 0.01865) < 1e-4, "패러데이 수소생산 계산 오류"

    # ── 6. 가능성 평가 ──
    print("\n" + "─"*72)
    print("[6] 가능성 평가 — '전자 진폭 파장' 촉매 접근의 의의와 한계")
    print("─"*72)
    print("  의의: ① Pt 우수성의 정성적 사실(화산 정점·d-밴드 최적)을 재현.")
    print("        ② λ_e 반파장 ≈ Pt-Pt 정합이라는 *공명 그림*을 제시(정합비≈1.0).")
    print("        ③ 인가전위로 λ_e 튜닝 → 전극설계·수전해 최적화의 구체적 지렛대.")
    print("        ④ 물 정수(저전압 수전해·살균)에 직접 응용 경로.")
    print("  한계: 진폭 파장 공명은 정성/스케일 일치 수준의 [H] 가설 — 정량 활성예측 아님.")
    print("        절대 활성·과전압은 측정 [CAL]. d-밴드/Sabatier가 정량 골격.")
    print("  결론: 가능성 있음. 공명 그림이 *튜닝 가설*을 주고 수전해/정수와 자연 연결.")
    print("        다음: λ_e 공명을 흡착에너지와 정량 연결(스케일링)하는 후속 연구.")

    print("\n" + "="*72)
    print("백금 촉매 요약:")
    print("  ① Pt = 5d hole로 페르미준위 d-상태 → 공여·역공여 준비된 금속촉매")
    print("  ② Sabatier 화산 정점: ΔG_H≈0 → HER 교환전류 최대 (확립)")
    print("  ③ d-밴드 중심 ε_d=-2.25eV 최적권 (확립)")
    print("  ④ 전자 진폭 파장 공명(VP): λ_e/2≈Pt-Pt 정합 → 역공여 공명 → 촉매 [H]")
    print("  ⑤ 인가전위로 λ_e 튜닝 = 수전해 전극 지렛대")
    print("  ⑥ 물 정수: 저과전압 HER 수전해(청정수소)+전기분해 살균, EM탈염과 통합")
    print("등급: [CAL] 화산·d-밴드·과전압 · [H] 전자 진폭 파장 공명·튜닝 · [F] 패러데이 생산")
    print("="*72)


if __name__ == "__main__":
    main()
