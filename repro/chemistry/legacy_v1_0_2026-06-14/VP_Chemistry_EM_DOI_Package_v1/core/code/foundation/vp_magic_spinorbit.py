# -*- coding: utf-8 -*-
"""
vp_magic_spinorbit.py — 노즐 비틀림(스핀-궤도)으로 50·126 복원 (재현가능·정직)
====================================================================
질문(사용자): 격자에 비틀림(노즐 방향성)을 더하면 50·126이 복원되는가?

답(정직): 부분적으로 — 메커니즘은 복원되나 매개변수-자유 닫힌형은 아니다.
  • 구면 가우스 격자(vp_gauss_shells): 2,8,20,28,82 (5/7) — 매개변수 0, 순수 기하.
  • 남은 50·126 = 고-j 침입궤도(1g9/2, 1i13/2). 스핀-궤도 L·S 결합이 만든다.
  • VP 노즐(C₃ 깨짐의 단일 체대각축) = 자연스러운 스핀 양자화 축 → L·S의 축을 제공.
  • 침입궤도 용량 2N+2 (N=4→10:50, N=6→14:126)가 닫힘을 만든다.
  • 단, 스핀-궤도 *세기*는 표준 핵물리(경험값) → 50·126은 구조적으론 노즐에서 grounded이나
    매개변수-자유 기하 닫힌형은 아니다. (무리한 7/7 기하주장 금지.)

등급: [F?] 구면격자 5/7(2,8,20,28,82) · [구조] 노즐축=스핀-궤도축, 침입 2N+2 →50·126
      [CAL] 궤도 순서/스핀-궤도 세기(표준 핵물리) · [O] 50·126의 매개변수-자유 기하 유도
실행: python3 vp_magic_spinorbit.py   (표준 라이브러리만)
"""
import math

MAGIC = [2, 8, 20, 28, 50, 82, 126]
LATTICE_HITS = [2, 8, 20, 28, 82]      # vp_gauss_shells.py 결과 (5/7)

# 표준 핵 껍질모형 궤도 순서 [CAL] (경험적 ordering; nlj, 용량 2j+1)
# 침입궤도(고-j, j=l+1/2, 이전 껍질로 내려옴)는 ↓ 표기
ORBITALS = [
    ("1s1/2", 2, False),
    ("1p3/2", 4, False), ("1p1/2", 2, False),
    ("1d5/2", 6, False), ("2s1/2", 2, False), ("1d3/2", 4, False),
    ("1f7/2", 8, True),                                    # N=3 침입 → 28
    ("2p3/2", 4, False), ("1f5/2", 6, False), ("2p1/2", 2, False), ("1g9/2",10, True),  # N=4 침입 → 50
    ("1g7/2", 8, False), ("2d5/2", 6, False), ("2d3/2", 4, False), ("3s1/2", 2, False), ("1h11/2",12,True), # N=5 → 82
    ("1h9/2",10, False), ("2f7/2", 8, False), ("2f5/2", 6, False), ("3p3/2", 4, False), ("3p1/2", 2, False), ("1i13/2",14,True), # N=6 → 126
]


def main():
    print("="*72)
    print("노즐 비틀림(스핀-궤도)으로 50·126 복원 — 정직한 탐색")
    print("="*72)

    print(f"\n[출발] 구면 가우스 격자(vp_gauss_shells): {LATTICE_HITS} (5/7, 매개변수 0)")
    print(f"       남은 마법수: {[m for m in MAGIC if m not in LATTICE_HITS]} → 스핀-궤도 필요")

    # ── 궤도 채움 → 마법수 닫힘 + 침입궤도 식별 ──
    print("\n[껍질모형 채움] 표준 궤도순서 [CAL] — 침입궤도(↓)가 닫힘을 만든다")
    print(f"  {'궤도':<8}{'용량':>4}{'누적':>5}  {'침입':>4} {'마법닫힘':>8}")
    print("  "+"-"*40)
    cum = 0; closures = []
    for name, cap, intruder in ORBITALS:
        cum += cap
        is_close = cum in MAGIC
        if is_close: closures.append((cum, name, intruder))
        mark = "★" + str(cum) if is_close else ""
        intr = "↓" if intruder else ""
        if is_close or intruder:
            print(f"  {name:<8}{cap:>4}{cum:>5}  {intr:>4} {mark:>8}")
    got = [c[0] for c in closures]
    print(f"\n  닫힘 = {got}   마법수 = {MAGIC}   적중 {len(got)}/7 ✓")

    # ── 침입궤도 = 50·126의 출처 ──
    print("\n[침입궤도] 고-j(j=l+1/2) 궤도가 이전 껍질로 내려와 닫힘 생성")
    print(f"  {'궤도':<8}{'l':>3}{'j':>5}{'용량 2N+2':>10}  만드는 마법수")
    print("  "+"-"*44)
    intr_map = [("1f7/2",3,"7/2",8,28),("1g9/2",4,"9/2",10,50),
                ("1h11/2",5,"11/2",12,82),("1i13/2",6,"13/2",14,126)]
    for name,l,j,cap,m in intr_map:
        src = "격자" if m in LATTICE_HITS else "노즐(스핀궤도)"
        print(f"  {name:<8}{l:>3}{j:>5}{cap:>10}  {m:<5} ({src})")
    print("  → 50(1g9/2)·126(1i13/2)이 노즐 스핀-궤도에서 복원. 28·82는 격자도 이미 가짐.")

    # ── VP 노즐 = 스핀-궤도 축 ──
    print("\n[VP 노즐 = 스핀-궤도 양자화 축]")
    print("  • 물리백서 §8.0.1: 연속 SO(2) 회전이 격자 C₃로 깔끔히 3분할 안 됨 → 잔여가")
    print("    단일 체대각축(노즐)에 집중. 이 노즐축이 L·S 결합의 자연 양자화 축.")
    print("  • L·S(고-j 정렬) 궤도가 노즐축 따라 낮아짐 → 침입 → 50·126.")
    print("  • 침입 용량 2N+2 ↔ VP n겹 구조(N섹터→N-1잠금; 여기선 j=N+1/2 stretched).")

    # ── 정직한 결론 ──
    print("\n[정직한 결론] 7/7 달성하되, 두 단계의 등급이 다르다")
    print(f"  • 구면 격자: 2,8,20,28,82 — 매개변수-자유 순수 기하 [F?].")
    print(f"  • 노즐 스핀-궤도: 50,126 — 메커니즘(침입+노즐축)은 grounded이나,")
    print(f"    궤도순서·스핀-궤도 세기는 표준 핵물리 [CAL]. 매개변수-자유 닫힌형 아님 [O].")
    print(f"  • 즉 '격자가 5개를 공짜로, 노즐이 나머지 2개의 구조를 준다'가 정직한 그림.")
    print(f"    50·126을 순수 π-기하로 닫는 것은 미해결 — 무리하게 주장 안 함.")

    print("\n" + "="*72)
    print("등급: [F?] 구면격자 5/7 · [구조] 노즐축=스핀궤도축 → 50·126 침입 메커니즘")
    print("      [CAL] 궤도순서·스핀궤도세기(표준 핵물리) · [O] 50·126 매개변수-자유 기하")
    print("      핵심: 격자(공짜 5개) + 노즐(나머지 2개 구조). 답=부분복원, 정직히 등급분리.")
    print("="*72)


if __name__ == "__main__":
    main()
