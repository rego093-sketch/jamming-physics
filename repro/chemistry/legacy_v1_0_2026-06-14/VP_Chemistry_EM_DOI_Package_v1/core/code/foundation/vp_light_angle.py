# -*- coding: utf-8 -*-
"""
vp_light_angle.py — VP 빛의 각도이론: 전파각 χ (재현가능·인과적)
====================================================================
물리백서 §10.9 + §14 + §15 학습 결과. 사용자 지침: 적외선을 정확히 알려면 이 이론을.

핵심: 빛 = 재밍격자에서 회전하는 양자들의 횡진동. 파장 λ의 운반자는 m개 회전양자가
      직렬로 늘어선 사슬(길이 mD, 빗변). 격자축 투영이 종방향 발판, 사슬에 누적된
      횡스윙이 한 파장(대변). 따라서 전파각:
            sinχ = 대변/빗변 = λ/(mD),   m = ⌈λ/D⌉,   D = 2λ_C,e
  • D = 전자 격자회전 지름 = 2λ_C,e = 6π⁶r_p (§3.4, 독립 삼각측량).
  • 짧은 λ(감마): m=1, χ→작음 = 종방향(관통). 긴 λ(가시·적외·전파): χ→90° = 횡방향.
  • χ=90° 도달 불가(종방향 성분이 0이면 전파 못함). m≥λ/D 이므로 sinχ≤1 자동.

회전 연결(§14): 광자=헬리시티 ±1(원편광=회전장). 전하=상쇄 안 된 회전.
                즉 빛도, 열도(vp_thermal), 입자도 모두 회전. 빛은 회전양자의 횡파.

등급: [F] sinχ=λ/(mD) (회전양자 사슬 기하, 두 모델식별 후 강제) ·
      [VP예측] χ(633)·χ(532) 전방예측(falsifier) · [개념] 흑체 ν²+강체차단
실행: python3 vp_light_angle.py   (표준 라이브러리만)
"""
import math
PI = math.pi
H  = 6.62607015e-34     # 플랑크 [J·s]
M_E= 9.1093837015e-31   # 전자질량 [kg]
C  = 2.99792458e8       # 빛속도 [m/s]
KB = 1.380649e-23

LAM_C = H/(M_E*C)       # 전자 비환산 콤프턴파장 [m] = 2.426e-12
D     = 2*LAM_C         # 격자회전 지름 [m] = 4.853e-12 (=2λ_C,e=6π⁶r_p)

def chi(lam_m):
    """전파각 χ [deg] from sinχ=λ/(mD), m=⌈λ/D⌉."""
    m = math.ceil(lam_m/D)
    s = lam_m/(m*D)
    return math.degrees(math.asin(min(1.0,s))), m, s

def cos_chi(lam_m):
    """종방향 성분 cosχ (관통성 지표)."""
    _,_,s = chi(lam_m); return math.sqrt(max(0.0,1-s*s))


def main():
    print("="*72)
    print("VP 빛의 각도이론 — 빛 = 회전양자 횡진동, 전파각 sinχ=λ/(mD)")
    print("="*72)
    print(f"\n격자회전 지름 D = 2λ_C,e = {D*1e12:.4f} pm  (=6π⁶r_p, 독립 삼각측량)")
    print(f"검증: 6π⁶·r_p = 6·π⁶·0.84125fm = {6*PI**6*0.84125:.1f} fm vs D={D*1e15:.1f} fm")
    print("\n빛 = m개 회전양자 사슬(길이 mD=빗변). 횡스윙 한파장(λ=대변) → sinχ=λ/(mD).")

    # ── EM 스펙트럼: 각도 (종방향→횡방향) ──
    print("\n[EM 스펙트럼] 전파각 χ: 짧은λ 종방향(관통) → 긴λ 횡방향")
    print(f"  {'영역':<10}{'λ':>10}{'m=⌈λ/D⌉':>16}{'χ[deg]':>9}{'cosχ(종)':>10}")
    print("  "+"-"*58)
    spectrum = [
        ("감마선",   1e-12,  "1 pm"),
        ("X선",      1e-10,  "0.1 nm"),
        ("자외선UV", 1e-7,   "100 nm"),
        ("가시광",   5.5e-7, "550 nm"),
        ("근적외NIR",1e-6,   "1 µm"),
        ("중적외MIR",1e-5,   "10 µm"),
        ("원적외FIR",1e-4,   "100 µm"),
        ("마이크로", 1e-2,   "1 cm"),
        ("전파",     1.0,    "1 m"),
    ]
    for name, lam, ls in spectrum:
        c,m,s = chi(lam); cc = math.sqrt(max(0,1-s*s))
        regime = "종방향" if c<45 else "횡방향"
        ms = f"{m:.3e}" if m >= 1e6 else str(m)
        print(f"  {name:<10}{ls:>10}{ms:>16}{c:>9.2f}{cc:>10.5f}  {regime}")
    print("  → 감마(χ≈12°) 종방향=관통, X선 전이대, 가시~전파 χ→90° 횡방향. [F]")
    print("    물리백서 정합: '감마는 근종방향, 가시·전파는 근횡방향'.")

    # ── 약속된 전방예측 (falsifier) ──
    print("\n[약속된 예측] HeNe 적·녹색 레이저 전파각 (전방예측 = falsifier)")
    for lam_nm in [632.8, 532.0]:
        c,m,s = chi(lam_nm*1e-9); cc=math.sqrt(max(0,1-s*s))
        print(f"  λ={lam_nm} nm:  m={m},  χ={c:.5f}°,  cosχ(종)={cc:.6f}")
    print("  → 길이(λ) 입력 → 각도(χ) 출력. 피팅 아닌 전방예측(D는 독립 결정).")

    # ── 적외선 정밀 (사용자 지침) ──
    print("\n[적외선 정밀] 긴 파장일수록 횡방향, cosχ(종) → 0")
    print(f"  {'적외선':<10}{'λ':>10}{'χ[deg]':>10}{'cosχ(종)':>12}{'90°-χ':>10}")
    print("  "+"-"*52)
    for name,lam in [("NIR 1µm",1e-6),("MIR 10µm",1e-5),("FIR 50µm",5e-5),("FIR 100µm",1e-4)]:
        c,m,s = chi(lam); cc=math.sqrt(max(0,1-s*s))
        print(f"  {name:<10}{lam*1e6:>8.0f}µm{c:>10.4f}{cc:>12.6f}{90-c:>10.4f}")
    print("  → 적외선은 90°에 매우 근접(횡파). cosχ(종방향)이 파장에 반비례로 감소.")
    print("    d-d 전이가 적외선(Cu·Ni)이면 이 각도이론으로 전파 특성 정량화. [F]")

    # ── 흑체: 모드밀도 + 강체차단 (§15) ──
    print("\n[흑체복사] 모드밀도 ∝ ν² + 강체껍질 고주파 차단 (§15)")
    print("  • 저주파: 기하적 모드 성장 ∝ ν² (Rayleigh-Jeans).")
    print("  • 고주파: 강체껍질이 고주파 변형 구조적 차단(ε_b=h_VP·ν > 열들뜸) → Planck 차단.")
    print("  • 둘의 곱 = Planck 스펙트럼. '고주파 절단은 빛의 신비가 아니라 격자 강체 필터'.")
    # Wien 변위: λ_peak·T = b
    b = 2.897771955e-3  # Wien 상수 [m·K]
    print(f"  Wien 변위 λ_peak·T = {b*1e3:.3f}×10⁻³ m·K:")
    for T,obj in [(5778,"태양표면"),(300,"상온체"),(2.7,"우주배경")]:
        lp = b/T
        c,m,s = chi(lp)
        print(f"    T={T}K ({obj}): λ_peak={lp*1e6:.2f}µm → χ={c:.3f}° (횡파)")
    print("  → 상온체 복사 피크(~10µm 적외선)도 횡파. 흑체=격자 모드 열들뜸(vp_thermal 연결).")

    # ── VP 통일 ──
    print("\n[VP 통일] 회전이 빛·열·전기를 하나로")
    print("  • 빛: 회전양자의 횡진동(χ→90°), 광자=헬리시티±1 회전장 (§14)")
    print("  • 전기: 같은 진동의 극종방향(χ→0), '전기는 감마선처럼 달린다' (§14 conduction)")
    print("  • 열: 회전·진동 들뜸(vp_thermal). 흑체=열들뜸의 복사.")
    print("  하나의 회전양자 격자가 각도 χ에 따라 빛↔전기, 진동으로 열을 낸다.")

    print("\n" + "="*72)
    print("등급: [F] sinχ=λ/(mD) (회전양자 사슬 기하) · [VP예측] χ(633)·χ(532) falsifier")
    print("      [개념] 흑체 ν²+강체차단·회전 통일 · D=2λ_C,e=6π⁶r_p 독립결정")
    print("      핵심: 빛=회전양자 횡파, 파장이 전파각 정함. 적외선=극횡파(χ→90°).")
    print("            빛·전기·열이 하나의 회전격자에서 각도 χ로 갈린다.")
    print("="*72)


if __name__ == "__main__":
    main()
