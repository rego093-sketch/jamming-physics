# -*- coding: utf-8 -*-
"""
vp_phase.py — VP 상전이 = 회전 대 응집 (재현가능·인과적)
====================================================================
주장: 상전이는 회전·진동 에너지(열)가 응집(재밍/결합)을 이기는 임계다.
  • 녹음(고체→액체): 진동 진폭이 원자간격의 임계분율(~0.1)에 도달 → 재밍 질서 붕괴 (Lindemann).
  • 끓음(액체→기체): 열에너지가 응집결합을 이김 → ΔS_vap≈일정 (Trouton, 응집 탈출 엔트로피).

인과 사슬(회전 관점, vp_thermal 잇기): 열 = 회전·진동 들뜸. 가열 → 진폭↑.
  진폭 √⟨u²⟩이 간격 a의 ~0.1 도달 = 재밍(φ=0.74,z=12) 풀림 = 녹음.
  ΔH_vap ≈ 응집에너지, ΔH_vap/T_b ≈ 88 J/mol·K = 응집 탈출의 보편 엔트로피.

등급: [F?] Lindemann 비 δ_L~0.1(금속 군집, θ_D [CAL]) · [F?] Trouton ΔS_vap~88(비회합액)
      [O] 회합액(물·알코올) H결합 초과 · 정밀 녹는점 절대값(θ_D 입력)
실행: python3 vp_phase.py   (표준 라이브러리만)
"""
import math
HBAR = 1.054571817e-34
KB   = 1.380649e-23
U_KG = 1.66053907e-27

def lindemann_ratio(theta_D, M_u, T_m, a_pm):
    """녹는점에서 진동 진폭/간격 = √⟨u²⟩/a (Debye 고온극한)."""
    M = M_u*U_KG; a = a_pm*1e-12
    u2 = 9*HBAR**2*T_m/(M*KB*theta_D**2)      # ⟨u²⟩ 고온극한
    return math.sqrt(u2)/a


def main():
    print("="*72)
    print("VP 상전이 = 회전 대 응집 — 열(회전·진동)이 재밍/결합을 이기는 임계")
    print("="*72)
    print("\n원리(vp_thermal 잇기): 열 = 회전·진동 들뜸. 가열 → 진폭↑.")
    print("  녹음 = 진폭이 간격의 ~0.1 도달(재밍 풀림). 끓음 = 열이 응집결합 이김.")

    # ── 녹음: Lindemann (재밍 풀림) ──
    print("\n[녹음 = Lindemann] 진동 진폭 √⟨u²⟩이 원자간격 a의 임계분율 δ_L 도달")
    print(f"  {'금속':<5}{'θ_D[K]':>7}{'M[u]':>7}{'T_m[K]':>8}{'a[pm]':>7}{'δ_L=u/a':>9}")
    print("  "+"-"*48)
    # (기호, Debye온도[K], 질량[u], 녹는점[K], 최근접거리[pm])
    metals = [("Cu",343,63.5,1358,256),("Al",428,27.0,933,286),("Au",165,197,1337,288),
              ("Pb",105,207.2,601,350),("Fe",470,55.8,1811,248),("W",400,183.8,3695,274),
              ("Ag",225,107.9,1235,289),("Ni",450,58.7,1728,249)]
    ratios=[]
    for sym,tD,M,Tm,a in metals:
        dL = lindemann_ratio(tD,M,Tm,a); ratios.append(dL)
        print(f"  {sym:<5}{tD:>7}{M:>7.1f}{Tm:>8}{a:>7}{dL:>9.3f}")
    avg=sum(ratios)/len(ratios)
    print("  "+"-"*48)
    print(f"  평균 δ_L = {avg:.3f} (범위 {min(ratios):.3f}~{max(ratios):.3f})")
    print(f"  → 다양한 금속이 δ_L≈0.1 근처 군집 = 보편 녹음 기준(진폭 ~간격의 10%).")
    print(f"    이것이 재밍(φ=0.74,z=12) 질서가 진동에 풀리는 기하 임계. [F?] (θ_D 입력 [CAL])")

    # ── 끓음: Trouton (응집 탈출) ──
    print("\n[끓음 = Trouton] ΔH_vap/T_b ≈ 일정 = 응집 탈출의 보편 엔트로피")
    print(f"  {'액체':<10}{'ΔHvap[kJ/mol]':>14}{'T_b[K]':>8}{'ΔSvap':>8}  비고")
    print("  "+"-"*52)
    # (이름, 증발열[kJ/mol], 끓는점[K])
    liquids = [("벤젠",30.8,353,""),("CCl4",30.0,350,""),("헥산",28.9,342,""),
               ("수은Hg",59.1,630,""),("아르곤Ar",6.5,87,""),("메탄CH4",8.2,112,""),
               ("물H2O",40.7,373,"H결합↑"),("에탄올",38.6,351,"H결합↑")]
    normal=[]
    for nm,dH,Tb,note in liquids:
        dS = dH*1000/Tb
        if not note: normal.append(dS)
        print(f"  {nm:<10}{dH:>14.1f}{Tb:>8}{dS:>8.0f}  {note}")
    avgT=sum(normal)/len(normal)
    print("  "+"-"*52)
    print(f"  비회합액 평균 ΔS_vap = {avgT:.0f} J/mol·K (Trouton≈88)")
    print(f"  → 비회합 액체는 ΔS_vap≈88 보편(응집 탈출 엔트로피 일정). [F?]")
    print(f"    물·에탄올은 초과(H결합 추가 질서) — 정직히 [O] 별도. 응집이 강하면 벗어남.")

    # ── 응집에너지 ↔ 증발열 ──
    print("\n[응집 ↔ 증발열] ΔH_vap ≈ 응집에너지 (액체 결합 끊기)")
    print("  • 끓음은 분자간 결합을 다 끊는 것 → ΔH_vap ~ 응집(반데르발스/H결합) 에너지.")
    print("  • 강한 결합(금속·이온) → 높은 끓는점; 약한 결합(분자결정) → 낮은 끓는점.")
    print("  • √2 결합파열·P_idx 극성이 응집 세기를 정함 → 끓는점 순서.")

    # ── VP 통일 ──
    print("\n[VP 통일] 회전(열) 대 응집(재밍/결합)의 경쟁이 상(phase)을 정함")
    print("  ┌────────┬──────────────────┬──────────────────────┐")
    print("  │ 상전이 │ 이기는 쪽         │ VP 임계              │")
    print("  ├────────┼──────────────────┼──────────────────────┤")
    print("  │ 녹음   │ 진동 > 재밍질서   │ δ_L≈0.1 (간격의 10%) │")
    print("  │ 끓음   │ 열 > 응집결합     │ ΔS_vap≈88 (Trouton)  │")
    print("  │ 승화   │ 진동 > 결합 직접  │ 둘의 결합            │")
    print("  └────────┴──────────────────┴──────────────────────┘")
    print("  열=회전 들뜸(vp_thermal), 응집=재밍(φ)+결합(√2). 상전이=둘의 임계 경쟁.")

    print("\n" + "="*72)
    print("등급: [F?] Lindemann δ_L≈0.1(금속 군집) · [F?] Trouton ΔS_vap≈88(비회합액)")
    print("      [O] 회합액 H결합 초과 · 정밀 절대 녹는점(θ_D [CAL] 입력)")
    print("      핵심: 상전이 = 회전(열) 대 응집(재밍/결합)의 임계. 열역학 회전관점의 연장.")
    print("="*72)


if __name__ == "__main__":
    main()
