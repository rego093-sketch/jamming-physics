# -*- coding: utf-8 -*-
"""
vp_crystal_packing.py — VP 결정 충전 기하: 고체 속 원자 배치 (재현가능·인과적)
====================================================================
주장: 고체에서 원자 배치는 구 충전 기하(케플러)다. 충전율·배위수가 기하에서 나오고,
      원자질량(주기율표) + 반지름 + 충전 → 물질 밀도를 예측한다.
      재밍 키스톤(φ=0.64,z=6, 비정질)과 결정(φ=0.74,z=12)이 같은 충전 기하의 두 극.

인과 사슬: 구 충전 기하 → 충전율 φ·배위수 z (순수 기하)
           → 밀도 ρ = (셀당 원자수·원자질량)/(셀 부피[반지름]).  원자질량은 VP(주기율표).

등급: [F] 충전율·배위수(순수 기하) · [F?] 금속 밀도(원자반지름 [CAL]) · 실측 대조.
실행: python3 vp_crystal_packing.py   (표준 라이브러리만)
"""
import math
PI = math.pi
NA = 6.02214076e23

# ── 충전 기하 (순수 기하, 자유계수 0) ──
PACKINGS = {
    # 이름: (셀당 원자수, a/r 관계함수, 배위수, 충전율)
    "FCC": dict(Z_cell=4, a_over_r=2*math.sqrt(2), z=12, phi=PI/(3*math.sqrt(2))),
    "HCP": dict(Z_cell=6, a_over_r=2.0,            z=12, phi=PI/(3*math.sqrt(2))),
    "BCC": dict(Z_cell=2, a_over_r=4/math.sqrt(3), z=8,  phi=PI*math.sqrt(3)/8),
    "SC":  dict(Z_cell=1, a_over_r=2.0,            z=6,  phi=PI/6),
}
# 재밍(비정질): 무작위 조밀충전
RCP = dict(z=6, phi=0.64)   # 키스톤 (물리백서)


def density(mass_u, r_pm, struct):
    """밀도 [g/cm³] = (셀당 원자수·질량)/(셀 부피).  FCC/BCC만 (a/r 사용)."""
    p = PACKINGS[struct]
    r_cm = r_pm*1e-10                       # pm → cm
    a = p["a_over_r"]*r_cm                  # 격자상수 [cm]
    V = a**3                                # 셀 부피
    m = p["Z_cell"]*mass_u/NA               # 셀당 질량 [g]
    return m/V

# 검증 금속: (기호, 원자질량[u], 금속반지름[pm], 구조, 실측밀도[g/cm³])
METALS = [
    ("Al", 26.98, 143, "FCC", 2.70),
    ("Cu", 63.55, 128, "FCC", 8.96),
    ("Au", 196.97,144, "FCC", 19.30),
    ("Ag", 107.87,144, "FCC", 10.49),
    ("Ni", 58.69, 124, "FCC", 8.90),
    ("Pb", 207.2, 175, "FCC", 11.34),
    ("Fe", 55.85, 126, "BCC", 7.87),
    ("Cr", 52.00, 128, "BCC", 7.19),
    ("W",  183.84,139, "BCC", 19.25),
]


def main():
    print("="*72)
    print("VP 결정 충전 기하 — 고체 속 원자 배치(구 충전)에서 밀도로")
    print("="*72)

    # ── 충전율·배위수 (순수 기하) ──
    print("\n[충전 기하] 충전율 φ·배위수 z (순수 기하, 자유계수 0)")
    print(f"  {'구조':<5}{'배위수 z':>8}{'충전율 φ':>10}  이상값")
    print("  "+"-"*40)
    ideal = {"FCC":0.7405,"HCP":0.7405,"BCC":0.6802,"SC":0.5236}
    for name,p in PACKINGS.items():
        print(f"  {name:<5}{p['z']:>8}{p['phi']:>10.4f}  {ideal[name]}")
    print(f"  {'RCP재밍':<5}{RCP['z']:>8}{RCP['phi']:>10.4f}  0.64 (키스톤, 비정질)")
    print(f"  → FCC/HCP φ=π/(3√2)={PI/(3*math.sqrt(2)):.4f} (최밀, 케플러). 전부 순수 기하 [F].")

    # ── 밀도 예측 ──
    print("\n[밀도 예측] ρ = (셀당 원자수·원자질량)/(셀 부피[반지름])  (실측 대조)")
    print(f"  {'금속':<5}{'구조':<5}{'질량[u]':>8}{'r[pm]':>7}{'ρ예측':>9}{'ρ실측':>9}{'Δ':>7}")
    print("  "+"-"*54)
    errs = []
    for sym, m, r, st, rho_meas in METALS:
        rho = density(m, r, st)
        d = (rho-rho_meas)/rho_meas*100; errs.append(abs(d))
        print(f"  {sym:<5}{st:<5}{m:>8.2f}{r:>7}{rho:>9.2f}{rho_meas:>9.2f}{d:>+6.0f}%")
    mae = sum(errs)/len(errs)
    print("  "+"-"*54)
    print(f"  평균절대오차 {mae:.0f}%. (오차원: 금속반지름 [CAL] 정의 산포 ~수%.)")
    print(f"  → 밀도가 충전기하(φ) + VP 원자질량 + 반지름으로 재현. 구조 차이(FCC vs BCC) 반영.")

    # ── 재밍 ↔ 결정 ──
    print("\n[재밍 ↔ 결정] 같은 충전 기하의 두 극")
    print("  ┌──────────────┬────────┬────────┬──────────────────────┐")
    print("  │ 상태         │ φ      │ z      │ VP 역할              │")
    print("  ├──────────────┼────────┼────────┼──────────────────────┤")
    print("  │ 비정질(재밍) │ 0.64   │ 6      │ 표면장력 0.92·녹는점  │")
    print("  │ 결정(FCC)    │ 0.74   │ 12     │ 밀도·강도·전위        │")
    print("  └──────────────┴────────┴────────┴──────────────────────┘")
    print("  φ=0.64(z=6)는 등방 재밍 임계, φ=0.74(z=12)는 최밀 결정. 같은 구충전, 다른 질서.")

    # ── 기하 통일 ──
    print("\n[기하 통일] 구면·격자·충전 — 하나의 기하 프로그램")
    print("  • 분자각: 구 *위* N점 재밍 (VSEPR) — vp_molecular_geometry")
    print("  • 핵껍질: 구 *안* 격자점 가우스 계수 (마법수) — vp_gauss_shells")
    print("  • 결정밀도: 구 충전 φ·z (본 모듈)")
    print("  세 가지 모두 '구와 격자의 기하' — 분자·핵·고체를 한 기하로.")

    print("\n" + "="*72)
    print("등급: [F] 충전율 φ·배위수 z (순수 기하, 케플러 최밀 π/(3√2))")
    print("      [F?] 금속 밀도 (φ + VP 질량 + 반지름[CAL]) · [O] 반지름 정의 산포")
    print("      핵심: 고체 속 원자 배치가 구충전 기하. 분자(구면)·핵(격자)·고체(충전) 기하 통일.")
    print("="*72)


if __name__ == "__main__":
    main()
