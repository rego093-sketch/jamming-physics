# -*- coding: utf-8 -*-
"""
vp_strength.py — VP 재료 이론강도 (재현가능·인과적) [티어 S1: 신소재로 가는 첫 다리]
====================================================================
주장: 재료의 이론강도(이상강도)는 §4 √2 대각 파열에서 나온다 — 핵분열 절단·분자해리와
      같은 파열 원리. 결합이 √2배 간격으로 늘면 파열하므로, 파열변형 ε_r = √2−1 ≈ 0.414.
      정현(Frenkel-Orowan) 응력-변형 포락선과 결합하면:

        σ_th = E · ε_r / π = E·(√2−1)/π ≈ E/7.6        (최대힘은 ε_r/2 ≈ 0.21 에서)

      → 무결함 재료의 강도/탄성계수 비는 ~1/7.6 (보편 기하). 실재료는 전위(결함)로
        그 1/10~1/1000 → 결함물리는 [O](분자 녹는점·핵 껍질처럼 정직히 분리).

인과 사슬: √2 대각(§4)[F] → 파열변형 ε_r=√2−1 → (정현포락선) → σ_th/E=(√2−1)/π.
           E(탄성계수)는 측정 [CAL]. 강도/E 비만이 VP 기하 산출.

검증 헤드라인: 그래핀(무결함 2D)이 이상강도에 도달 — σ_int/E 측정 ≈ 0.12 vs VP 0.132.
실행: python3 vp_strength.py   (표준 라이브러리만)
"""
import math

SQRT2 = math.sqrt(2)
EPS_R = SQRT2 - 1                 # 파열변형 = √2 신장 (§4) = 0.4142
RATIO_VP = EPS_R / math.pi        # σ_th/E = (√2−1)/π = 0.1318  (≈ E/7.59)
STRAIN_MAXF = EPS_R / 2           # 최대힘(=관측 파괴) 변형 ≈ 0.207


def sigma_theoretical(E_GPa):
    """이론(이상) 인장강도 [GPa] = E·(√2−1)/π."""
    return E_GPa * RATIO_VP


# 검증 데이터: (재료, E[GPa], 측정 이상/내재 강도[GPa], 측정 파괴변형, 메모)
#   무결함(그래핀·CNT·휘스커)일수록 VP 이상강도에 접근. 벌크는 전위로 급락[O].
MATERIALS = [
    ("그래핀",      1015, 125,  0.25, "무결함 2D — 천장 도달 (Lee 2008)"),
    ("탄소나노튜브", 1000, 110,  0.15, "무결함 1D — 천장의 ~0.83"),
    ("다이아몬드",  1100, 95,   0.13, "이상강도 계산 산포 90-200; 천장의 ~0.65"),
    ("SiC 휘스커",  450,  21,   0.06, "휘스커 — 결함 잔존, 천장의 ~0.36"),
    ("실리콘 휘스커",170,  7.6,  0.07, "Si 휘스커 — 천장의 ~0.34"),
    ("강철(벌크)",  200,  0.5,  0.002,"전위 多 → 천장의 ~1/250 [O]"),
    ("알루미늄(벌크)",70,  0.05, 0.001,"전위 多 → 천장의 ~1/180 [O]"),
]


def main():
    print("="*72)
    print("VP 재료 이론강도 — √2 대각 파열이 이상강도를 정한다 (핵분열·분자해리와 동일 원리)")
    print("="*72)

    print("\n[유도] √2 → 이상강도")
    print(f"  파열변형  ε_r = √2−1 = {EPS_R:.4f}   (결합이 √2배 간격으로 신장하면 파열, §4 [F])")
    print(f"  정현포락선 σ(ε)=σ_th·sin(πε/ε_r) → E=σ_th·π/ε_r")
    print(f"  ⇒ σ_th/E = (√2−1)/π = {RATIO_VP:.4f}  (≈ E/{1/RATIO_VP:.1f})")
    print(f"  최대힘(관측 파괴) 변형 = ε_r/2 = {STRAIN_MAXF:.3f}")

    print("\n[검증] VP 0.132 = 이상강도 천장(상한). 재료 완전도가 도달률을 정한다.")
    print(f"  {'재료':<12} {'E[GPa]':>7} {'σ_th(VP)':>9} {'σ측정':>7} {'측정/E':>7} {'VP비':>6}  메모")
    print("  "+"-"*92)
    for name, E, s_meas, eps_f, note in MATERIALS:
        s_vp = sigma_theoretical(E)
        ratio_meas = s_meas/E
        print(f"  {name:<12} {E:>7.0f} {s_vp:>9.1f} {s_meas:>7.1f} {ratio_meas:>7.3f} {RATIO_VP:>6.3f}  {note}")
    print("  자기비평: 그래핀만 천장에 도달(Δ7%). 휘스커/벌크는 결함으로 그 아래 — 즉 0.132는")
    print("            '예측'이 아니라 '상한'이며, 도달률(완전도)은 결함밀도가 정한다. 이것이 설계 여지다.")

    # ── 헤드라인 검증: 그래핀 ──
    E_g, s_g = 1015, 125
    s_vp_g = sigma_theoretical(E_g)
    print(f"\n[헤드라인] 그래핀(무결함 2D): VP 이상강도 {s_vp_g:.0f} GPa vs 측정 내재강도 {s_g} GPa")
    print(f"  Δ = {100*(s_vp_g-s_g)/s_g:+.1f}%  → √2 대각 파열이 그래핀 강도를 예측. ★")
    print(f"  측정 파괴변형 ~0.25 ↔ VP 최대힘 변형 {STRAIN_MAXF:.2f} (정현 봉우리).")

    # ── 결함 간극 = [O] ──
    print("\n[결함 간극 — [O]] 벌크 재료가 이상강도에 못 미치는 이유")
    for name, E, s_meas, *_ in [("강철(벌크)",200,0.5),("알루미늄(벌크)",70,0.05)]:
        s_vp = sigma_theoretical(E)
        knockdown = s_vp/s_meas
        print(f"  {name:<12} 이상 {s_vp:.0f} GPa / 실측 {s_meas} GPa = {knockdown:.0f}× 격하 (전위·결정립계)")
    print("  → 격하는 결함밀도가 정한다(전위론). VP는 이상한계를 [F]로 주고, 결함은 [O]로 둔다.")
    print("    이것이 분자해리의 '촉매=기하압축기', 핵분열의 '껍질효과'와 같은 자리의 열린항이다.")

    # ── 통일 ──
    print("\n[통일] √2 대각 파열의 세 척도")
    print("  ┌──────────┬──────────────────┬───────────────────────────┐")
    print("  │ 척도     │ 파열 단위        │ √2 한계                   │")
    print("  ├──────────┼──────────────────┼───────────────────────────┤")
    print("  │ 핵       │ 핵자 접촉(목)    │ 절단점 신장 (vp_fission)   │")
    print("  │ 분자     │ 결합 진폭        │ √2·r_eff 천장 (§4)        │")
    print("  │ 재료     │ 원자면 결합      │ σ_th=E·(√2−1)/π (본 모듈) │")
    print("  └──────────┴──────────────────┴───────────────────────────┘")

    print("\n" + "="*72)
    print("등급: [F] 파열변형 ε_r=√2−1(§4) · [F?] σ_th/E=(√2−1)/π=0.132 vs 그래핀 0.123(Δ7%)")
    print("      [CAL] 탄성계수 E(재료별 측정) · [O] 결함 격하(전위밀도→실강도)")
    print("      핵심: 신소재 강도 설계의 상한이 √2에서 나온다. 다음 — 탄성계수 자체를 재밍에서(S2).")
    print("="*72)


if __name__ == "__main__":
    main()
